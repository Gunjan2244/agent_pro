"""Builds the Agent PRO app icon from its geometry (docs/DESIGN_SYSTEM.md, App icon).

The glyph is a rounded "A" whose crossbar is a rising chart line ending in a dot, on the
108x108dp adaptive-icon canvas. Strokes are turned into one flat even-odd outline, so the
same path works for the coloured foreground and the Android 13+ monochrome layer.

Run from the repo root (needs shapely, cairosvg and pillow, e.g. in a throwaway venv):
    python design/app-icon/build_icon.py

Writes:
    design/app-icon/agent-pro-icon.svg       master: glyph on the primary background
    design/app-icon/agent-pro-glyph.svg      glyph only, transparent
    design/app-icon/play-store-512.png       Play Store listing icon (full-bleed square)
    design/app-icon/app-store-1024.png       iOS App Store icon (no alpha)
    design/app-icon/preview.png              circle/squircle masks and 96/48/24px sizes
    mobile/androidApp/src/main/res/drawable/ic_launcher_{foreground,monochrome}.xml
"""
import math
from pathlib import Path

import cairosvg
from PIL import Image, ImageDraw
from shapely.affinity import translate
from shapely.geometry import LineString, MultiPolygon, Point

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "design/app-icon"
RES = ROOT / "mobile/androidApp/src/main/res/drawable"

BG = "#1F4AA8"  # `primary` in shared/design-tokens.json
C = 54.0  # canvas centre
SAFE_R = 33.0  # adaptive-icon safe zone: a 66dp circle

LEG_W = 8.5
CHART_W = 3.6
DOT_R = 3.8
GAP = 2.2  # background-coloured gap between the chart line and the legs
QS = 4  # 16-gon curves: under 0.4px off at the largest launcher size, and the path stays under lint's 800-char VectorPath limit
CHART = [(38.8, 67.5), (47.5, 60.5), (53, 63.5), (67.5, 53.5)]
DOT = (70.5, 51)


def stroke(points, width, extra=0.0):
    return LineString(points).buffer(width / 2 + extra, quad_segs=QS, cap_style="round", join_style="round")


legs = stroke([(35.5, 73), (54, 33), (72.5, 73)], LEG_W)
knock = stroke(CHART, CHART_W, GAP).union(Point(DOT).buffer(DOT_R + GAP, quad_segs=QS))
glyph = legs.difference(knock).union(stroke(CHART, CHART_W)).union(Point(DOT).buffer(DOT_R, quad_segs=QS))
minx, miny, maxx, maxy = glyph.bounds
glyph = translate(glyph, C - (minx + maxx) / 2, C - (miny + maxy) / 2).simplify(0.05)

polys = list(glyph.geoms) if isinstance(glyph, MultiPolygon) else [glyph]
far = max(math.dist((C, C), p) for poly in polys for p in poly.exterior.coords)
assert far <= SAFE_R, f"glyph leaves the safe zone ({far:.2f} > {SAFE_R})"


def ring(coords):
    pts = [f"{x:.1f},{y:.1f}" for x, y in list(coords)[:-1]]
    return "M" + " ".join(pts) + "Z"  # points after M are implicit line-tos


d = "".join(ring(p.exterior.coords) + "".join(ring(i.coords) for i in p.interiors) for p in polys)


def svg(view=(0, 0, 108, 108), bg=True):
    x, y, w, h = view
    rect = f'<rect x="0" y="0" width="108" height="108" fill="{BG}"/>' if bg else ""
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{x} {y} {w} {h}">{rect}'
            f'<path fill="#FFFFFF" fill-rule="evenodd" d="{d}"/></svg>')


def vector_drawable(comment):
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by design/app-icon/build_icon.py; don't edit by hand (docs/DESIGN_SYSTEM.md, App icon). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="#FFFFFF"
        android:fillType="evenOdd"
        android:pathData="{d}" />
</vector>
"""


(OUT / "agent-pro-icon.svg").write_text(svg())
(OUT / "agent-pro-glyph.svg").write_text(svg(bg=False))
(RES / "ic_launcher_foreground.xml").write_text(vector_drawable(
    'Launcher icon foreground: the white "A" with a rising chart line, inside the 66dp safe zone.'))
(RES / "ic_launcher_monochrome.xml").write_text(vector_drawable(
    "Launcher icon monochrome layer (Android 13+ themed icons): the same glyph; the launcher tints it."))

# The visible part of an adaptive icon is the middle 72dp; the store icons use that crop, full-bleed.
visible = svg((18, 18, 72, 72)).encode()
cairosvg.svg2png(bytestring=visible, write_to=str(OUT / "play-store-512.png"), output_width=512, output_height=512)
cairosvg.svg2png(bytestring=visible, write_to=str(OUT / "app-store-1024.png"), output_width=1024, output_height=1024)
big = Image.open(OUT / "app-store-1024.png").convert("RGB")
big.save(OUT / "app-store-1024.png")


def masked(shape):
    m = Image.new("L", big.size, 0)
    if shape == "circle":
        ImageDraw.Draw(m).ellipse((0, 0, 1023, 1023), fill=255)
    else:
        ImageDraw.Draw(m).rounded_rectangle((0, 0, 1023, 1023), radius=300, fill=255)
    im = Image.new("RGBA", big.size, (0, 0, 0, 0))
    im.paste(big, mask=m)
    return im


sheet = Image.new("RGBA", (1100, 420), (236, 238, 242, 255))
for i, shape in enumerate(["circle", "squircle"]):
    sheet.alpha_composite(masked(shape).resize((300, 300), Image.LANCZOS), (30 + i * 330, 60))
x = 700
for s in (96, 48, 24):
    sheet.alpha_composite(masked("circle").resize((s, s), Image.LANCZOS), (x, 160))
    x += s + 40
sheet.save(OUT / "preview.png")
print(f"OK: farthest point {far:.2f}dp from centre (safe zone {SAFE_R}dp), path {len(d)} chars")

/**
 * The read-only offline cache (Room KMP with the bundled SQLite driver; DECISIONS #8). Screens render
 * from its Flows; [SyncEngine] fills it. Each feature adds its entities and DAOs here.
 *
 * The cache can always be rebuilt from Supabase, so a schema change drops and re-creates it
 * (destructive migration) and the sync cursors are reset (`AppContainer`, [StoreKeys.CACHE_SCHEMA_VERSION]).
 */
@Database(
    entities = [
        ProfileEntity::class,
        SiteEntity::class,
        SiteDailyViewEntity::class,
        EnquiryEntity::class,
        CustomerEntity::class,
        CustomerDraftEntity::class,
        PolicyEntity::class,
        PremiumPaymentEntity::class,
    ],
    version = AppDatabase.VERSION,
    exportSchema = true,
)
@ConstructedBy(AppDatabaseConstructor::class)
abstract class AppDatabase : RoomDatabase() {
    abstract fun profileDao(): ProfileDao
    abstract fun siteDao(): SiteDao
    abstract fun enquiryDao(): EnquiryDao
    abstract fun customerDao(): CustomerDao
    abstract fun customerDraftDao(): CustomerDraftDao
    abstract fun policyDao(): PolicyDao
    abstract fun premiumPaymentDao(): PremiumPaymentDao
    abstract fun siteDailyViewDao(): SiteDailyViewDao

    companion object {
        /** 2: site_daily_views (Phase 8); enquiries, customers, policies, premium_payments (Phases 6–7). 3: customer_drafts. */
        const val VERSION = 3
        const val FILE_NAME = "agentpro.db"
    }
}

/** Generated by Room's KSP processor for each target (the one expect/actual Room requires). */
@Suppress("NO_ACTUAL_FOR_EXPECT", "KotlinNoActualForExpect")
expect object AppDatabaseConstructor : RoomDatabaseConstructor<AppDatabase> {
    override fun initialize(): AppDatabase
}

/** Finishes a platform's database builder: bundled SQLite, IO dispatcher, destructive schema changes. */
fun buildAppDatabase(builder: RoomDatabase.Builder<AppDatabase>): AppDatabase = builder
    .setDriver(BundledSQLiteDriver())
    .setQueryCoroutineContext(Dispatchers.IO)
    .fallbackToDestructiveMigration(dropAllTables = true)
    .build()

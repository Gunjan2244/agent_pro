package com.sledje.agentpro.buildlogic.codegen

/** Name conventions shared by the generators and the verifier (docs/SHARED_DEFINITIONS.md). */
object Naming {
    /** Package of the generated Compose resource accessors (`Res`). */
    const val RES_PACKAGE = "com.sledje.agentpro.resources"
    const val CATALOG_PACKAGE = "com.sledje.agentpro.core.catalog"
    const val DESIGN_PACKAGE = "com.sledje.agentpro.core.designsystem"
    const val FORMS_PACKAGE = "com.sledje.agentpro.core.forms"
    const val CONFIG_PACKAGE = "com.sledje.agentpro.app"

    /** i18n key -> Compose resource name: `cat_` + key with dots turned into underscores. */
    fun stringResourceName(i18nKey: String): String = "cat_" + i18nKey.replace('.', '_')

    /** Icon name -> drawable resource name (`composeResources/drawable/ic_<name>.xml`). */
    fun drawableName(icon: String): String = "ic_$icon"

    val RESOURCE_NAME = Regex("^[A-Za-z_][A-Za-z0-9_]*$")
    val ICON_NAME = Regex("^[a-z0-9_]+$")

    /** Catalog list name -> Kotlin type name, e.g. enquiryStatuses -> EnquiryStatus, templateFamilies -> TemplateFamily, features -> FeatureId, locales -> AppLocale. */
    fun catalogTypeName(listName: String): String {
        overrides[listName]?.let { return it }
        val singular = when {
            listName.endsWith("uses") -> listName.dropLast(2)          // statuses -> status
            listName.endsWith("ies") -> listName.dropLast(3) + "y"     // templateFamilies -> templateFamily
            listName.endsWith("ches") || listName.endsWith("shes") || listName.endsWith("xes") -> listName.dropLast(2)
            listName.endsWith("s") -> listName.dropLast(1)             // sources -> source
            else -> listName
        }
        return singular.replaceFirstChar { it.uppercaseChar() }
    }

    // `locales` -> AppLocale, so the enum never clashes with java.util.Locale or Compose's Locale.
    private val overrides = mapOf("features" to "FeatureId", "locales" to "AppLocale")

    /** Stable key -> enum constant name: follow_up -> FollowUp, siteBuilder -> SiteBuilder, next_3_months -> Next3Months. */
    fun enumConstant(key: String): String {
        val name = key.split('_', '-', '.').filter { it.isNotEmpty() }
            .joinToString("") { part -> part.replaceFirstChar { it.uppercaseChar() } }
        return if (name.firstOrNull()?.isDigit() == true) "_$name" else name
    }

    /** JSON object key -> Kotlin object name: service -> Service. */
    fun objectName(key: String): String = enumConstant(key)

    /** JSON key -> Kotlin property name; keeps camelCase, converts snake_case. */
    fun propertyName(key: String): String {
        val parts = key.split('_', '-').filter { it.isNotEmpty() }
        val name = parts.first() + parts.drop(1).joinToString("") { p -> p.replaceFirstChar { it.uppercaseChar() } }
        return if (name.first().isDigit()) "_$name" else name
    }

    /** Kotlin string literal with escaping. */
    fun kotlinString(value: String): String = buildString {
        append('"')
        for (c in value) when (c) {
            '\\' -> append("\\\\")
            '"' -> append("\\\"")
            '\n' -> append("\\n")
            '\r' -> append("\\r")
            '\t' -> append("\\t")
            '$' -> append("\\$")
            else -> if (c < ' ') append("\\u%04x".format(c.code)) else append(c)
        }
        append('"')
    }

    const val GENERATED_HEADER =
        "// GENERATED by mobile/build-logic (./gradlew generateShared) from shared/*.json. Do not edit.\n"
}

package com.sledje.agentpro.buildlogic.codegen

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.jsonObject
import java.io.File

/** Privacy notice hashes: notice key -> version -> locale -> sha256. */
typealias NoticeHashes = Map<String, Map<Int, Map<String, String>>>

/**
 * `mobile/build-logic/catalog-keys.lock.json`: every catalog key ever released, per list. Committed.
 * `generateShared` only ever adds keys to it; `verifyShared` fails when a locked key disappears from
 * catalog.json (it must stay, marked `"deprecated": true`) or when a catalog key isn't locked yet.
 *
 * It also holds `privacyNoticeHashes` (notice key -> version -> locale -> sha256): the text hash of every
 * notice version ever generated. A locked version's hashes never change: `verifyShared` fails when a
 * notice's text changes without a new `version`, and catalog_sync keeps old versions resolvable.
 */
object CatalogKeysLock {
    const val FILE_NAME = "catalog-keys.lock.json"
    private const val NOTICES = "privacyNoticeHashes"

    fun read(file: File): Map<String, List<String>> {
        if (!file.isFile) return emptyMap()
        val root = Json.parseToJsonElement(file.readText()).jsonObject
        val lists = root.obj("lists") ?: return emptyMap()
        return lists.mapValues { (_, v) -> (v as JsonArray).map { it.primitiveString()!! } }
    }

    fun readNoticeHashes(file: File): NoticeHashes {
        if (!file.isFile) return emptyMap()
        val root = Json.parseToJsonElement(file.readText()).jsonObject
        val notices = root.obj(NOTICES) ?: return emptyMap()
        return notices.mapValues { (_, versions) ->
            (versions as JsonObject).entries.associate { (v, locales) ->
                v.toInt() to (locales as JsonObject).mapValues { it.value.primitiveString()!! }
            }
        }
    }

    /** Lock contents after adding the current catalog keys (existing order kept, new keys appended). */
    fun merged(existing: Map<String, List<String>>, defs: SharedDefinitions): Map<String, List<String>> {
        val result = LinkedHashMap<String, List<String>>()
        existing.forEach { (k, v) -> result[k] = v }
        defs.catalogLists.forEach { list ->
            val old = result[list.jsonName].orEmpty()
            result[list.jsonName] = old + list.keys.filterNot { it in old }.distinct()
        }
        return result
    }

    /**
     * Notice hashes after adding each current notice version that isn't locked yet. A version that is
     * already locked is never overwritten (a changed text must get a new version instead).
     */
    fun mergedNoticeHashes(existing: NoticeHashes, defs: SharedDefinitions): NoticeHashes {
        val result = LinkedHashMap<String, Map<Int, Map<String, String>>>()
        existing.forEach { (k, v) -> result[k] = v }
        PrivacyNotices(defs).current.forEach { (key, versions) ->
            val old = result[key].orEmpty()
            val added = versions.filterKeys { it !in old }.filterValues { it.isNotEmpty() }
            if (added.isNotEmpty() || key !in result) result[key] = (old + added).toSortedMap()
        }
        return result.filterValues { it.isNotEmpty() }
    }

    fun render(lock: Map<String, List<String>>, noticeHashes: NoticeHashes = emptyMap()): String {
        val fields = linkedMapOf(
            "comment" to JsonPrimitive(
                "GENERATED by ./gradlew generateShared. Every catalog key ever released; keys are only added. " +
                    "Commit this file. Remove a key from shared/catalog.json by marking it \"deprecated\": true instead."
            ),
            "lists" to JsonObject(lock.mapValues { (_, keys) -> JsonArray(keys.map { JsonPrimitive(it) }) }),
        )
        if (noticeHashes.isNotEmpty()) {
            fields[NOTICES] = JsonObject(noticeHashes.mapValues { (_, versions) ->
                JsonObject(versions.toSortedMap().entries.associate { (v, locales) ->
                    v.toString() to JsonObject(locales.mapValues { JsonPrimitive(it.value) })
                })
            })
        }
        return pretty.encodeToString(JsonObject.serializer(), JsonObject(fields)) + "\n"
    }

    private val pretty = Json { prettyPrint = true; prettyPrintIndent = "  " }
}

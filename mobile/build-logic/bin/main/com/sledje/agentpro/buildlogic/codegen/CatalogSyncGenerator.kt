package com.sledje.agentpro.buildlogic.codegen

import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import java.io.File
import java.time.Instant
import java.time.ZoneOffset
import java.time.format.DateTimeFormatter

/**
 * Plans and renders `supabase/migrations/<yyyyMMddHHmmss>_catalog_sync.sql`.
 *
 * Rules (docs/SHARED_DEFINITIONS.md, Codegen):
 * - Skipped (nothing written) while `supabase/migrations/` has no schema migration, i.e. no `*.sql`
 *   other than `*_catalog_sync.sql`: the tables it alters don't exist yet.
 * - Written only when the hash of catalog.json + site-schema.json + templates/index.json differs from
 *   the hash recorded in the latest existing catalog_sync file (`-- catalog-hash: sha256:<hex>`).
 * - Deprecated keys stay valid in the CHECK constraints (old rows keep them) and in
 *   `catalog_interest_keys_all()`; `catalog_interest_keys()` lists active keys only.
 * - With `privacyNotices`, it also emits the notice functions (current version + every released hash) and,
 *   with `dataRequestKinds`/`dataRequestStatuses`, their key functions; `retention` joins the app_config upsert.
 */
class CatalogSyncGenerator(
    private val defs: SharedDefinitions,
    /** The lockfile's `privacyNoticeHashes`, so notice versions released earlier stay resolvable. */
    private val noticeLock: NoticeHashes = emptyMap(),
    private val clock: () -> Instant = Instant::now,
) {
    sealed interface Plan {
        data class Skipped(val reason: String) : Plan
        data class UpToDate(val file: File) : Plan
        data class Write(val fileName: String, val content: String) : Plan
    }

    fun plan(migrationsDir: File): Plan {
        if (Migrations.schemaMigrations(migrationsDir).isEmpty()) {
            return Plan.Skipped(
                "no schema migrations in ${migrationsDir.path} yet; catalog_sync is written once the tables exist"
            )
        }
        val latest = Migrations.latestCatalogSync(migrationsDir)
        if (latest != null && Migrations.readHash(latest) == defs.catalogHash) return Plan.UpToDate(latest)
        return Plan.Write(fileName(migrationsDir), sql())
    }

    private fun fileName(migrationsDir: File): String {
        val now = clock().atOffset(ZoneOffset.UTC).format(TIMESTAMP).toLong()
        val newest = Migrations.all(migrationsDir).mapNotNull { Migrations.timestamp(it) }.maxOrNull()
        val ts = if (newest != null && newest >= now) {
            // Keep a valid date-time: one second after the newest migration.
            runCatching {
                java.time.LocalDateTime.parse(newest.toString(), TIMESTAMP).plusSeconds(1).format(TIMESTAMP)
            }.getOrElse { (newest + 1).toString() }
        } else now.toString()
        return "${ts}_catalog_sync.sql"
    }

    fun sql(): String {
        val sb = StringBuilder()
        sb.append("-- GENERATED by mobile/build-logic (./gradlew generateShared) from shared/catalog.json,\n")
        sb.append("-- shared/site-schema.json and shared/templates/index.json. Do not edit; change the JSON and regenerate.\n")
        sb.append("-- ${Migrations.HASH_PREFIX}${defs.catalogHash}\n")
        if (PrivacyNotices(defs).present) sb.append("-- Privacy notice hashes come from catalog.privacyNotices + shared/i18n and the keys lockfile.\n")
        sb.append('\n')

        sb.append("-- CHECK constraints for enum-like columns (deprecated keys stay valid).\n")
        for (c in CHECKS) {
            val values = checkValues(c)
            val name = "${c.table}_${c.column}_check"
            sb.append("alter table public.${c.table} drop constraint if exists $name;\n")
            sb.append("alter table public.${c.table} add constraint $name check (${c.column} in (${values.joinToString(", ") { lit(it) }}));\n")
        }
        sb.append('\n')

        val interests = defs.catalogList("interests")!!
        sb.append("-- Interest whitelist used by submit_enquiry (active keys only; deprecated ones can't be submitted).\n")
        sb.append(function("catalog_interest_keys()", "text[]", textArray(interests.activeKeys)))
        sb.append("-- Every interest key, deprecated ones included; used by publish_site so existing content still publishes.\n")
        sb.append(function("catalog_interest_keys_all()", "text[]", textArray(interests.keys)))

        val modes = defs.catalogList("premiumModes")!!
        val cases = modes.entries.joinToString(" ") { "when ${lit(it.string("key")!!)} then ${it.long("months")!!}" }
        sb.append("-- Months per premium mode (catalog.premiumModes[].months); null for an unknown mode.\n")
        sb.append(function("catalog_premium_mode_months(p_mode text)", "integer", "select case p_mode $cases else null end"))

        val reserved = reservedSlugs()
        sb.append("-- Slugs no agent can use (catalog.reservedSlugs); used by private.is_reserved_slug.\n")
        sb.append(function("catalog_reserved_slugs()", "text[]", textArray(reserved)))

        val schemaText = defs.siteSchemaText.trim()
        val inner = dollarTag("site_schema", schemaText)
        sb.append("-- shared/site-schema.json verbatim, for publish_site validation.\n")
        sb.append(function("site_schema()", "jsonb", "select $inner$schemaText$inner::jsonb"))

        appendPrivacy(sb)

        val features = defs.catalogList("features")!!
        val flags = JsonObject(features.entries.associate { it.string("key")!! to JsonPrimitive(it.bool("default") ?: false) })
        val pricing = defs.catalog.obj("pricing") ?: throw IllegalArgumentException("catalog.json has no \"pricing\" object")
        sb.append("-- Feature flag defaults and server-authoritative prices. Manual flag overrides live in the\n")
        sb.append("-- `flag_overrides` row, which this never touches (effective flags: public.effective_flags()).\n")
        sb.append("insert into public.app_config (key, value) values\n")
        sb.append("  ('flags', ${lit(flags.toString())}::jsonb),\n")
        val retention = defs.catalog["retention"]
        if (retention != null && retention !is JsonObject) throw IllegalArgumentException("catalog.json: \"retention\" must be an object")
        sb.append("  ('pricing', ${lit(pricing.toString())}::jsonb)")
        if (retention != null) sb.append(",\n  ('retention', ${lit(retention.toString())}::jsonb)")
        sb.append("\non conflict (key) do update set value = excluded.value;\n")
        return sb.toString()
    }

    /**
     * Privacy (docs/PRIVACY.md): notice lookups for record_consent / submit_enquiry, and the data-request keys
     * for submit_data_request / resolve_data_request. Functions only: the CHECKs on consents.notice_key,
     * data_requests.kind and data_requests.status are added to [CHECKS] once P1-2 has created those tables.
     */
    private fun appendPrivacy(sb: StringBuilder) {
        val pn = PrivacyNotices(defs)
        if (pn.present) {
            val active = pn.notices.filterNot { it.deprecated }
            val cases = active.joinToString(" ") { n ->
                val hashes = pn.hashes(n)
                require(hashes.keys == pn.locales.toSet()) { "catalog.privacyNotices.${n.key}: text missing for ${pn.locales - hashes.keys}" }
                val obj = JsonObject(mapOf("version" to JsonPrimitive(n.version)) + hashes.entries.associate { (l, h) -> "hash_$l" to JsonPrimitive(h) })
                "when ${lit(n.key)} then ${lit(obj.toString())}::jsonb"
            }
            sb.append("-- Current version of an active privacy notice: {version, hash_<locale>...}; null if unknown or deprecated.\n")
            sb.append(function("catalog_privacy_notice(p_key text)", "jsonb",
                if (cases.isEmpty()) "select null::jsonb" else "select case p_key $cases else null end"))

            val rows = pn.released(noticeLock).flatMap { (key, versions) ->
                versions.flatMap { (v, locales) -> locales.map { (l, h) -> "(${lit(key)}, $v, ${lit(l)}, ${lit(h)})" } }
            }
            val values = if (rows.isEmpty()) " (null::text, null::integer, null::text, null::text)"
            else rows.joinToString(",\n    ", "\n    ", "\n  ")
            sb.append("-- Text hash of a released notice version in a locale (every version ever generated); null if unknown.\n")
            sb.append(function("catalog_privacy_notice_hash(p_key text, p_version integer, p_locale text)", "text",
                "select t.h from (values$values) as t(k, v, l, h)\n  where t.k = p_key and t.v = p_version and t.l = p_locale"))
            sb.append("-- The locale whose text of this released notice version has this hash; null if none (an invalid hash).\n")
            sb.append(function("catalog_privacy_notice_locale(p_key text, p_version integer, p_hash text)", "text",
                "select t.l from (values$values) as t(k, v, l, h)\n  where t.k = p_key and t.v = p_version and t.h = p_hash"))
        }
        defs.catalogList("dataRequestKinds")?.let {
            sb.append("-- Data request kinds a new request may use (active keys only).\n")
            sb.append(function("catalog_data_request_kinds()", "text[]", textArray(it.activeKeys)))
        }
        defs.catalogList("dataRequestStatuses")?.let {
            sb.append("-- Data request statuses a request may be set to (active keys only).\n")
            sb.append(function("catalog_data_request_statuses()", "text[]", textArray(it.activeKeys)))
        }
    }

    private fun checkValues(c: Check): List<String> {
        val values = if (c.source == TEMPLATES) defs.templateKeys
        else (defs.catalogList(c.source) ?: throw IllegalArgumentException("catalog.json has no \"${c.source}\" list")).keys
        require(values.isNotEmpty()) { "${c.table}.${c.column}: no values in ${c.source}" }
        return values
    }

    private fun reservedSlugs(): List<String> {
        val array = defs.catalog["reservedSlugs"] as? JsonArray
            ?: throw IllegalArgumentException("catalog.json has no \"reservedSlugs\" array")
        return array.map {
            requireNotNull(it.primitiveString()) { "catalog.reservedSlugs: only strings are allowed" }
        }
    }

    private fun textArray(values: List<String>) = "select array[${values.joinToString(", ") { lit(it) }}]::text[]"

    private fun function(signature: String, returns: String, body: String): String {
        val outer = dollarTag("", body)
        val name = signature.substringBefore('(')
        val argTypes = signature.substringAfter('(').substringBefore(')').split(',')
            .map { it.trim().substringAfterLast(' ') }.filter { it.isNotEmpty() }.joinToString(", ")
        return buildString {
            append("create or replace function public.$signature\n")
            append("returns $returns\nlanguage sql\nimmutable\nset search_path = ''\n")
            append("as $outer\n  $body\n$outer;\n")
            append("revoke all on function public.$name($argTypes) from public, anon, authenticated;\n\n")
        }
    }

    /**
     * A dollar-quote tag that doesn't occur in [content]: `$$` (empty base) or `$<base>$`, then
     * `$<base or fn><n>$` with n = 1, 2, ... until there is no collision.
     */
    internal fun dollarTag(base: String, content: String): String {
        var i = 0
        while (true) {
            val name = when {
                i == 0 -> base
                base.isEmpty() -> "fn$i"
                else -> "$base$i"
            }
            val tag = "\$$name\$"
            if (!content.contains(tag)) return tag
            i++
        }
    }

    private fun lit(s: String) = "'" + s.replace("'", "''") + "'"

    /** [source] is a catalog list name, or [TEMPLATES] for the keys of templates/index.json. */
    private class Check(val table: String, val column: String, val source: String)

    companion object {
        private val TIMESTAMP: DateTimeFormatter = DateTimeFormatter.ofPattern("yyyyMMddHHmmss")
        private const val TEMPLATES = "templates/index.json"
        private val CHECKS = listOf(
            Check("enquiries", "status", "enquiryStatuses"),
            Check("enquiries", "interest", "interests"),
            Check("enquiries", "source", "enquirySources"),
            Check("policies", "premium_mode", "premiumModes"),
            Check("policies", "status", "policyStatuses"),
            Check("site_domains", "status", "domainStatuses"),
            Check("sites", "template_key", TEMPLATES),
            Check("sites", "accent", "accentSwatches"),
            Check("sites", "locale", "locales"),
            Check("profiles", "preferred_language", "locales"),
        )
    }
}

/** Reading `supabase/migrations/`. */
object Migrations {
    const val SUFFIX = "_catalog_sync.sql"
    const val HASH_PREFIX = "catalog-hash: sha256:"

    fun all(dir: File): List<File> =
        dir.listFiles { f -> f.isFile && f.name.endsWith(".sql") }?.sortedBy { it.name }.orEmpty()

    fun schemaMigrations(dir: File): List<File> = all(dir).filterNot { it.name.endsWith(SUFFIX) }

    fun latestCatalogSync(dir: File): File? = all(dir).filter { it.name.endsWith(SUFFIX) }.maxByOrNull { it.name }

    fun readHash(file: File): String? = file.useLines { lines ->
        lines.take(20).firstNotNullOfOrNull { line ->
            line.substringAfter(HASH_PREFIX, "").trim().takeIf { it.isNotEmpty() }
        }
    }

    /** Leading numeric timestamp of a migration file name, e.g. 20261015120000_init.sql -> 20261015120000. */
    fun timestamp(file: File): Long? = file.name.takeWhile { it.isDigit() }.takeIf { it.isNotEmpty() }?.toLongOrNull()
}

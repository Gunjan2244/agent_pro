-- offers: transitions draft -> live -> archived -> draft (new offers start as drafts); localized content against
-- offer_schema() (drafts may be incomplete; going live needs every required field in every locale); the public text
-- check (DECISIONS #77: no blocked term or company name in any localized field, in any locale, nor in the link or
-- image URL; checked on insert, when one of them changes, and again on going live, since a company may have been
-- added meanwhile; never on other updates, so archiving always works); CTA kind, interest and validity rules;
-- stamps published_at/by and archived_at. internal_name (admin-only) is not checked: it's the real name.
-- Public text error: blocked_term:<field>:<locale>:<term> (22023), field an offer-schema key (locale en, hi, …) or
-- cta_url / image_url (empty locale).
create or replace function private.offers_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_schema  jsonb := public.offer_schema();
  v_locales text[] := public.catalog_locales();
  v_limits  jsonb := public.catalog_offer_limits();
  v_old     text := case when tg_op = 'UPDATE' then old.status end;
  v_spec    jsonb;
  v_loc     text;
  v_key     text;
  v_val     jsonb;
  v_terms   text[];
  v_hit     text;
begin
  if tg_op = 'INSERT' and new.status <> 'draft' then
    raise exception 'invalid_transition' using errcode = 'P0001', detail = 'a new offer starts as a draft';
  end if;
  if tg_op = 'UPDATE' then
    if new.company_id <> old.company_id then
      raise exception 'invalid_company' using errcode = '22023';
    end if;
    if new.status <> v_old and not (
         (v_old = 'draft' and new.status = 'live')
      or (v_old = 'live' and new.status = 'archived')
      or (v_old = 'archived' and new.status = 'draft')) then
      raise exception 'invalid_transition' using errcode = 'P0001', detail = v_old || ' -> ' || new.status;
    end if;
  end if;

  -- Content shape (every status): catalog locales only; known localized keys; strings within maxLength.
  if jsonb_typeof(new.content) <> 'object' then
    raise exception 'invalid_content' using errcode = '22023';
  end if;
  for v_loc in select jsonb_object_keys(new.content) loop
    if not v_loc = any (v_locales) or jsonb_typeof(new.content -> v_loc) <> 'object' then
      raise exception 'invalid_content' using errcode = '22023', detail = v_loc;
    end if;
    for v_key, v_val in select e.key, e.value from jsonb_each(new.content -> v_loc) e loop
      select s into v_spec from jsonb_array_elements(v_schema -> 'localized') s where s ->> 'key' = v_key;
      if v_spec is null or jsonb_typeof(v_val) not in ('string', 'null')
         or (jsonb_typeof(v_val) = 'string' and char_length(v_val #>> '{}') > (v_spec ->> 'maxLength')::int) then
        raise exception 'invalid_content' using errcode = '22023', detail = v_loc || '.' || v_key;
      end if;
    end loop;
  end loop;

  if tg_op = 'INSERT' or new.content is distinct from old.content or new.cta_url is distinct from old.cta_url
     or new.image_url is distinct from old.image_url or (new.status = 'live' and v_old is distinct from 'live') then
    v_terms := private.public_text_terms();
    for v_loc, v_key, v_val in
      select l.key, e.key, e.value
        from jsonb_each(new.content) l, jsonb_each(l.value) e
       where jsonb_typeof(e.value) = 'string'
       order by array_position(v_locales, l.key),
                (select s.ord from jsonb_array_elements(v_schema -> 'localized') with ordinality s(spec, ord)
                  where s.spec ->> 'key' = e.key) loop
      v_hit := private.public_text_match(v_val #>> '{}', v_terms);
      if v_hit is not null then
        raise exception 'blocked_term:%:%:%', v_key, v_loc, v_hit using errcode = '22023', detail = v_loc || '.' || v_key;
      end if;
    end loop;
    v_hit := private.public_text_match(new.cta_url, v_terms);
    if v_hit is not null then
      raise exception 'blocked_term:cta_url::%', v_hit using errcode = '22023', detail = 'cta_url';
    end if;
    v_hit := private.public_text_match(new.image_url, v_terms);
    if v_hit is not null then
      raise exception 'blocked_term:image_url::%', v_hit using errcode = '22023', detail = 'image_url';
    end if;
  end if;

  if (tg_op = 'INSERT' or new.cta_kind is distinct from old.cta_kind)
     and not new.cta_kind = any (coalesce(public.catalog_offer_cta_kinds(), '{}'::text[])) then
    raise exception 'invalid_cta' using errcode = '22023';
  end if;
  if new.interest is not null and not new.interest = any (coalesce(public.catalog_interest_keys_all(), '{}'::text[])) then
    raise exception 'invalid_interest' using errcode = '22023';
  end if;
  if new.ends_at - new.starts_at > make_interval(days => coalesce((v_limits ->> 'maxValidityDays')::int, 366)) then
    raise exception 'invalid_dates' using errcode = '22023', detail = 'longer than catalog.offers.maxValidityDays';
  end if;

  if new.status = 'live' then
    for v_loc in select unnest(v_locales) loop
      for v_spec in select s from jsonb_array_elements(v_schema -> 'localized') s
                     where coalesce((s ->> 'required')::boolean, false) loop
        if btrim(coalesce(new.content #>> array[v_loc, v_spec ->> 'key'], '')) = '' then
          raise exception 'incomplete_content' using errcode = '22023', detail = v_loc || '.' || (v_spec ->> 'key');
        end if;
      end loop;
    end loop;
    if new.cta_kind = 'link' and new.cta_url is null then
      raise exception 'invalid_cta' using errcode = '22023', detail = 'a link needs an https URL';
    end if;
    if new.ends_at <= now() and (v_old is distinct from 'live' or new.ends_at <> old.ends_at) then
      raise exception 'offer_ended' using errcode = '22023';
    end if;
  end if;

  -- Stamps are set here only (they aren't in the column grants).
  if tg_op = 'UPDATE' then
    new.published_at := old.published_at;
    new.published_by := old.published_by;
    new.archived_at := old.archived_at;
  else
    new.published_at := null;
    new.published_by := null;
    new.archived_at := null;
  end if;
  if new.status = 'live' and v_old is distinct from 'live' then
    new.published_at := now();
    new.published_by := auth.uid();
  elsif new.status = 'archived' and v_old is distinct from 'archived' then
    new.archived_at := now();
  elsif new.status = 'draft' and v_old = 'archived' then
    new.archived_at := null;
  end if;
  return new;
end;
$$;


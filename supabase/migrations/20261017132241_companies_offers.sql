-- {membership, offers}: the current request or link (or, without one, the latest rejection or revocation), and the
-- company's live offers that haven't ended, only while the link is approved and the company active. Works on a
-- lapsed plan (read-only).
create or replace function public.my_company_offers()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_uid    uuid := private.require_uid();
  v_mem    public.company_memberships := private.current_membership(v_uid);
  v_offers jsonb := '[]'::jsonb;
begin
  if v_mem.id is null then
    select m.* into v_mem from public.company_memberships m
     where m.agent_id = v_uid
     order by m.requested_at desc, m.created_at desc limit 1;
    if v_mem.status not in ('rejected', 'revoked') then
      v_mem := null;
    end if;
  end if;

  if v_mem.status = 'approved' and exists (select 1 from public.companies c where c.id = v_mem.company_id and c.is_active) then
    select coalesce(jsonb_agg(jsonb_build_object(
             'id', o.id, 'content', o.content, 'image_url', o.image_url, 'cta_kind', o.cta_kind, 'cta_url', o.cta_url,
             'interest', o.interest, 'starts_at', o.starts_at, 'ends_at', o.ends_at, 'phase', private.offer_phase(o))
             order by o.sort, o.starts_at, o.id), '[]'::jsonb)
      into v_offers
      from public.offers o
     where o.company_id = v_mem.company_id and o.status = 'live' and o.ends_at > now();
  end if;

  return jsonb_build_object('membership', private.membership_json(v_mem), 'offers', v_offers);
end;
$$;


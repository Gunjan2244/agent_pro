-- A per-locale text object ({"en": "…", "hi": "…"}): only catalog locales, strings of at most p_max characters,
-- and (with p_all) a non-blank value for every locale.
create or replace function private.valid_localized(p_value jsonb, p_max int, p_all boolean)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_locales text[] := public.catalog_locales();
  k text;
begin
  if p_value is null or jsonb_typeof(p_value) <> 'object' then
    return false;
  end if;
  for k in select jsonb_object_keys(p_value) loop
    if not k = any (v_locales) or jsonb_typeof(p_value -> k) <> 'string' or char_length(p_value ->> k) > p_max then
      return false;
    end if;
  end loop;
  if p_all and exists (select 1 from unnest(v_locales) l where btrim(coalesce(p_value ->> l, '')) = '') then
    return false;
  end if;
  return true;
end;
$$;

-- ---------------------------------------------------------------------------
-- Public text check (DECISIONS #77): public offer text never names a product or an insurer. Mirrors PublicText in
-- mobile/build-logic/.../codegen/SiteSeedKotlinGenerator.kt (the seed check and the web tests use the same rule).
-- ---------------------------------------------------------------------------

-- The terms public text may not contain, normalized (NFC, lowercase, trimmed) and unique, in check order: the
-- catalog's blocked terms (catalog.publicTextRules.blockedTerms) in list order, then every company's name in every
-- locale, active or not. Security invoker: only SECURITY DEFINER code calls it. plpgsql, because
-- catalog_blocked_terms() comes from the catalog_sync that sorts after this file.
create or replace function private.public_text_terms()
returns text[]
language plpgsql
stable
set search_path = ''
as $$
begin
  return (select coalesce(array_agg(t.term order by t.src, t.ord), '{}'::text[])
    from (select distinct on (x.term) x.term, x.src, x.ord
            from (select lower(normalize(btrim(b.term), NFC)) as term, 1 as src, b.ord
                    from unnest(coalesce(public.catalog_blocked_terms(), '{}'::text[])) with ordinality b(term, ord)
                  union all
                  select lower(normalize(btrim(n.value), NFC)), 2, row_number() over (order by c.sort, c.slug, n.key)
                    from public.companies c, jsonb_each_text(c.name) n) x
           where x.term <> ''
           order by x.term, x.src, x.ord) t);
end;
$$;

-- The first of p_terms (already normalized as above) that p_text contains, or null:
--   * both sides NFC and lowercase;
--   * a term's words match across any run of whitespace;
--   * the characters before and after the match must not be word characters (PublicText's \p{L}\p{M}\p{N}), so
--     "lic" doesn't match inside "public", and "एलआईसी" doesn't match inside a longer word or next to a vowel sign
--     or virama. Postgres regex has no \p{..} and [:alnum:] depends on the database's ctype, so the word class
--     also lists, by code point: Latin-1 and Latin Extended-A/B letters (U+00C0–U+024F without × and ÷), combining
--     diacritics (U+0300–U+036F) and the Devanagari block (U+0900–U+0963 letters, vowel signs, virama, nukta;
--     U+0966–U+096F digits; U+0971–U+097F letters), leaving out the dandas (U+0964/5) and U+0970 (punctuation).
-- Lookaround-free: (^|[^W])term([^W]|$); regex metacharacters in a term are escaped ("[." would start a collating
-- element, hence the bracket order). A cheap strpos() on the first word skips most terms.
create or replace function private.public_text_match(p_text text, p_terms text[])
returns text
language plpgsql
stable
set search_path = ''
as $$
declare
  v_w     text := '[:alnum:]' || chr(192) || '-' || chr(214) || chr(216) || '-' || chr(246) || chr(248) || '-' || chr(591)
                   || chr(768) || '-' || chr(879) || chr(2304) || '-' || chr(2403) || chr(2406) || '-' || chr(2415)
                   || chr(2417) || '-' || chr(2431);
  v_text  text;
  v_term  text;
  v_words text[];
  v_body  text;
begin
  if p_text is null or btrim(p_text) = '' then
    return null;
  end if;
  v_text := lower(normalize(p_text, NFC));
  foreach v_term in array coalesce(p_terms, '{}'::text[]) loop
    v_words := regexp_split_to_array(btrim(coalesce(v_term, '')), '[[:space:]]+');
    if v_words[1] is null or v_words[1] = '' or strpos(v_text, v_words[1]) = 0 then
      continue;
    end if;
    select string_agg(regexp_replace(u.w, '([]^$*+?(){}|.[\\])', '\\\1', 'g'), '[[:space:]]+' order by u.i)
      into v_body
      from unnest(v_words) with ordinality u(w, i);
    if v_text ~ ('(^|[^' || v_w || '])' || v_body || '([^' || v_w || ']|$)') then
      return v_term;
    end if;
  end loop;
  return null;
end;
$$;

-- The first blocked term or company name in txt, or null (the matcher above against public_text_terms()).
create or replace function private.public_text_violation(txt text)

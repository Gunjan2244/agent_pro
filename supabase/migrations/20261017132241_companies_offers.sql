-- publish_site from *_rpcs.sql, plus the offer checks. Returns {ok:true, published_at[, warnings]} or
-- {ok:false, errors:[{section, field, item, rule}]}.
create or replace function public.publish_site()
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_uid    uuid := private.require_uid();
  v_site   public.sites;
  v_errs   jsonb;
  v_offers jsonb;
  v_now    timestamptz := now();
begin
  perform private.require_can_write();
  select s.* into v_site from public.sites s
   where s.agent_id = v_uid and s.deleted_at is null
   for update;
  if v_site.id is null then
    raise exception 'not_found' using errcode = 'P0002';
  end if;

  v_offers := private.validate_site_offers(v_uid, v_site.draft_content);
  v_errs := private.validate_site_content(v_site.draft_content) || (v_offers -> 'errors');
  if jsonb_array_length(v_errs) > 0 then
    return jsonb_build_object('ok', false, 'errors', v_errs);
  end if;

  update public.sites
     set published_content = draft_content,
         published_at = v_now,
         is_published = true
   where id = v_site.id;
  if jsonb_array_length(v_offers -> 'warnings') > 0 then
    return jsonb_build_object('ok', true, 'published_at', v_now, 'warnings', v_offers -> 'warnings');
  end if;
  return jsonb_build_object('ok', true, 'published_at', v_now);
end;
$$;


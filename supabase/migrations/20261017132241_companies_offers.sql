-- Decide a pending request (approve | reject with a reason from catalog_membership_reject_reasons()) or revoke an
-- approved link (a note is required). note <= 200, shown to the agent. Returns the membership.
-- Errors: forbidden (42501), not_found (P0002, also for another company's request), invalid_decision /
-- invalid_reason / invalid_note (22023), invalid_transition (P0001).
create or replace function public.admin_review_membership(membership_id uuid, decision text, reject_reason text, note text)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_uid    uuid := private.require_admin();
  v_m      public.company_memberships;
  v_note   text := nullif(btrim(coalesce(admin_review_membership.note, '')), '');
  v_reason text := nullif(btrim(coalesce(admin_review_membership.reject_reason, '')), '');
  v_status text;
begin
  select m.* into v_m from public.company_memberships m where m.id = admin_review_membership.membership_id for update;
  if v_m.id is null or not public.is_admin_for(v_m.company_id) then
    raise exception 'not_found' using errcode = 'P0002';
  end if;
  if v_note is not null and char_length(v_note) > 200 then
    raise exception 'invalid_note' using errcode = '22023';
  end if;

  case admin_review_membership.decision
    when 'approve' then
      v_status := 'approved';
      v_reason := null;
    when 'reject' then
      v_status := 'rejected';
      if v_reason is null or not v_reason = any (coalesce(public.catalog_membership_reject_reasons(), '{}'::text[])) then
        raise exception 'invalid_reason' using errcode = '22023';
      end if;
    when 'revoke' then
      v_status := 'revoked';
      v_reason := null;
      if v_note is null then
        raise exception 'invalid_note' using errcode = '22023', detail = 'a revocation needs a note';
      end if;
    else
      raise exception 'invalid_decision' using errcode = '22023';
  end case;
  if (v_status in ('approved', 'rejected') and v_m.status <> 'pending')
     or (v_status = 'revoked' and v_m.status <> 'approved') then
    raise exception 'invalid_transition' using errcode = 'P0001', detail = v_m.status || ' -> ' || v_status;
  end if;

  update public.company_memberships m
     set status = v_status, reject_reason = v_reason, review_note = v_note
   where m.id = v_m.id
  returning * into v_m;
  return private.membership_json(v_m);
end;
$$;

-- Link a pending "not listed" request to a company (owners and unscoped editors), leaving it pending for review.
create or replace function public.admin_link_membership(membership_id uuid, company_id uuid)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_uid uuid := private.require_admin();
  v_m   public.company_memberships;
begin
  if not public.is_admin_for(null) then
    raise exception 'forbidden' using errcode = '42501';
  end if;
  select m.* into v_m from public.company_memberships m where m.id = admin_link_membership.membership_id for update;
  if v_m.id is null then
    raise exception 'not_found' using errcode = 'P0002';
  end if;
  if v_m.status <> 'pending' or v_m.company_id is not null then
    raise exception 'invalid_transition' using errcode = 'P0001';
  end if;
  if not exists (select 1 from public.companies c where c.id = admin_link_membership.company_id and c.is_active) then
    raise exception 'not_found' using errcode = 'P0002', detail = 'company';
  end if;
  update public.company_memberships m set company_id = admin_link_membership.company_id
   where m.id = v_m.id
  returning * into v_m;
  return private.membership_json(v_m);
end;
$$;

-- The review queue, oldest first (at most 200): requests for company_id (null = every company the admin may see,
-- unlisted ones included for unscoped admins) in status (default pending). Only the agent fields an admin needs
-- to verify (PRIVACY.md): name, designation, city, email, plus the agency code from the request, and the agent's
-- previous decided request.
create or replace function public.admin_membership_queue(company_id uuid, status text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_uid    uuid := private.require_admin();
  v_status text := coalesce(nullif(btrim(coalesce(admin_membership_queue.status, '')), ''), 'pending');
begin
  return coalesce((
    select jsonb_agg(jsonb_build_object(
             'id', q.id, 'company_id', q.company_id, 'suggested_name', q.suggested_name, 'status', q.status,
             'agency_code', q.agency_code, 'requested_at', q.requested_at, 'reviewed_at', q.reviewed_at,
             'reject_reason', q.reject_reason, 'review_note', q.review_note,
             'agent', jsonb_build_object('full_name', p.full_name, 'designation', p.designation, 'city', p.city, 'email', p.email),
             'previous', (select jsonb_build_object('status', x.status, 'company_id', x.company_id,
                                                    'reject_reason', x.reject_reason, 'reviewed_at', x.reviewed_at)
                            from public.company_memberships x
                           where x.agent_id = q.agent_id and x.id <> q.id and x.status in ('approved', 'rejected', 'revoked')
                           order by coalesce(x.reviewed_at, x.requested_at) desc limit 1))
             order by q.requested_at, q.id)
      from (select m.* from public.company_memberships m
             where m.status = v_status
               and public.is_admin_for(m.company_id)
               and (admin_membership_queue.company_id is null or m.company_id = admin_membership_queue.company_id)
             order by m.requested_at, m.id
             limit 200) q
      left join public.profiles p on p.id = q.agent_id), '[]'::jsonb);
end;
$$;

-- How many sites place an offer: {published_sites, draft_sites} counts only, never which agents (minimisation).
create or replace function public.admin_offer_usage(offer_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_uid     uuid := private.require_admin();
  v_company uuid;
  v_vars    jsonb := jsonb_build_object('id', admin_offer_usage.offer_id::text);
  v_path    jsonpath := '$.hero.featuredOffer ? (@.source == "company" && @.id == $id)';
  v_list    jsonpath := '$.offers.items[*] ? (@.source == "company" && @.id == $id)';
begin
  select o.company_id into v_company from public.offers o where o.id = admin_offer_usage.offer_id;
  if v_company is null or not public.is_admin_for(v_company) then
    raise exception 'not_found' using errcode = 'P0002';
  end if;
  return jsonb_build_object(
    'published_sites', (select count(*) from public.sites s
                         where s.deleted_at is null and s.is_published and s.published_content is not null
                           and (jsonb_path_exists(s.published_content, v_path, v_vars) or jsonb_path_exists(s.published_content, v_list, v_vars))),
    'draft_sites', (select count(*) from public.sites s
                     where s.deleted_at is null
                       and (jsonb_path_exists(s.draft_content, v_path, v_vars) or jsonb_path_exists(s.draft_content, v_list, v_vars))));
end;
$$;


-- companies: names in every catalog locale (<= 80), disclaimers (<= 300) per locale. The disclaimer is shown on
-- sites, so it passes the public text check (DECISIONS #77) against the blocked terms and every company's name,
-- this company's own (new) name included: a disclaimer must never name an insurer. Checked when the disclaimer or
-- the name changes. Error: blocked_term:disclaimer:<locale>:<term> (22023).
create or replace function private.companies_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_terms text[];
  v_loc   text;
  v_val   text;
  v_hit   text;
begin
  if not private.valid_localized(new.name, 80, true) then
    raise exception 'invalid_name' using errcode = '22023';
  end if;
  if new.disclaimer is not null and not private.valid_localized(new.disclaimer, 300, false) then
    raise exception 'invalid_disclaimer' using errcode = '22023';
  end if;
  if new.disclaimer is not null
     and (tg_op = 'INSERT' or new.disclaimer is distinct from old.disclaimer or new.name is distinct from old.name) then
    v_terms := private.public_text_terms()
      || coalesce((select array_agg(lower(normalize(btrim(n.value), NFC)) order by n.key)
                     from jsonb_each_text(new.name) n where btrim(n.value) <> ''), '{}'::text[]);
    for v_loc, v_val in select d.key, d.value from jsonb_each_text(new.disclaimer) d order by d.key loop
      v_hit := private.public_text_match(v_val, v_terms);
      if v_hit is not null then
        raise exception 'blocked_term:disclaimer:%:%', v_loc, v_hit using errcode = '22023', detail = v_loc || '.disclaimer';
      end if;
    end loop;
  end if;
  return new;
end;
$$;


-- company_memberships (written only by the RPCs below; this is defence in depth): new rows are pending for an
-- active company; pending -> approved | rejected | withdrawn, approved -> revoked | withdrawn; the company can be
-- set once on a pending "not listed" row (admin_link_membership); reviews are stamped.
create or replace function private.memberships_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    if new.status <> 'pending' then
      raise exception 'invalid_transition' using errcode = 'P0001';
    end if;
  else
    if new.agent_id <> old.agent_id then
      raise exception 'invalid_transition' using errcode = 'P0001';
    end if;
    if new.company_id is distinct from old.company_id
       and not (old.company_id is null and old.status = 'pending' and new.status = 'pending') then
      raise exception 'invalid_transition' using errcode = 'P0001', detail = 'the company can only be set on a pending unlisted request';
    end if;
    if new.status <> old.status and not (
         (old.status = 'pending' and new.status in ('approved', 'rejected', 'withdrawn'))
      or (old.status = 'approved' and new.status in ('revoked', 'withdrawn'))) then
      raise exception 'invalid_transition' using errcode = 'P0001', detail = old.status || ' -> ' || new.status;
    end if;
    if new.status in ('approved', 'rejected', 'revoked') and new.status <> old.status then
      new.reviewed_at := now();
      new.reviewed_by := auth.uid();
    else
      new.reviewed_at := old.reviewed_at;
      new.reviewed_by := old.reviewed_by;
    end if;
    new.requested_at := old.requested_at;
  end if;
  if new.company_id is not null and new.status in ('pending', 'approved')
     and (tg_op = 'INSERT' or new.company_id is distinct from old.company_id or new.status <> old.status)
     and not exists (select 1 from public.companies c where c.id = new.company_id and c.is_active) then
    raise exception 'not_found' using errcode = 'P0002', detail = 'company';
  end if;
  if new.status = 'approved' and new.company_id is null then
    raise exception 'invalid_transition' using errcode = 'P0001', detail = 'link the request to a company first';
  end if;
  return new;
end;
$$;

create trigger memberships_guard before insert or update on public.company_memberships
  for each row execute function private.memberships_guard();

-- Audit trail (shared with PRIVACY.md): one audit_log row per insert or real change, with the changed columns
-- and their new values. Memberships leave out the agency code, suggested name and review note (minimisation).
create or replace function private.audit_row()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_new     jsonb := to_jsonb(new);
  v_old     jsonb := case when tg_op = 'UPDATE' then to_jsonb(old) else '{}'::jsonb end;
  v_skip    text[] := array['created_at', 'updated_at', 'created_by', 'updated_by'];
  v_changes jsonb;
  v_uid     uuid := auth.uid();
  v_kind    text;
  v_action  text;
  v_ip      inet;
  v_status  text := v_new ->> 'status';
  v_was     text := v_old ->> 'status';
begin
  if tg_table_name = 'company_memberships' then
    v_skip := v_skip || array['agency_code', 'suggested_name', 'review_note'];
  end if;
  select jsonb_object_agg(e.key, e.value) into v_changes
    from jsonb_each(v_new) e
   where not e.key = any (v_skip)
     and (tg_op = 'INSERT' or e.value is distinct from v_old -> e.key);
  if tg_op = 'UPDATE' and v_changes is null then
    return null;
  end if;

  v_action := case tg_table_name
    when 'companies' then case when tg_op = 'INSERT' then 'company.create' else 'company.update' end
    when 'offers' then case
      when tg_op = 'INSERT' then 'offer.create'
      when v_status = 'live' and v_was = 'draft' then 'offer.go_live'
      when v_status = 'archived' and v_was = 'live' then 'offer.archive'
      when v_status = 'draft' and v_was = 'archived' then 'offer.restore'
      else 'offer.update' end
    when 'admins' then case
      when tg_op = 'INSERT' then 'admin.create'
      when v_new ->> 'revoked_at' is not null and v_old ->> 'revoked_at' is null then 'admin.revoke'
      else 'admin.update' end
    when 'company_memberships' then case
      when tg_op = 'INSERT' then 'membership.request'
      when v_status = 'approved' and v_was <> 'approved' then 'membership.approve'
      when v_status = 'rejected' and v_was <> 'rejected' then 'membership.reject'
      when v_status = 'revoked' and v_was <> 'revoked' then 'membership.revoke'
      when v_status = 'withdrawn' and v_was <> 'withdrawn' then 'membership.withdraw'
      when v_new -> 'company_id' is distinct from v_old -> 'company_id' then 'membership.link'
      else 'membership.update' end
  end;

  v_kind := case
    when v_uid is null then 'system'
    when exists (select 1 from public.admins a where a.user_id = v_uid and a.revoked_at is null) then 'admin'
    else 'agent'
  end;
  if v_kind = 'admin' then
    begin
      v_ip := nullif(btrim(split_part(current_setting('request.headers', true)::jsonb ->> 'x-forwarded-for', ',', 1)), '')::inet;
    exception when others then
      v_ip := null;
    end;
  end if;

  insert into public.audit_log (actor_id, actor_kind, action, entity, entity_id, changes, request_ip)
  values (v_uid, v_kind, v_action, tg_table_name,
          coalesce(v_new ->> 'id', v_new ->> 'user_id')::uuid, v_changes, v_ip);
  return null;
end;
$$;

do $$
declare
  t text;
begin
  foreach t in array array['companies', 'offers', 'admins', 'company_memberships'] loop
    execute format(
      'create trigger audit_row after insert or update on public.%I
         for each row execute function private.audit_row()', t);
  end loop;
end;
$$;


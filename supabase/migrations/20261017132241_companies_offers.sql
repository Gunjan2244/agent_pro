-- validate_fields from *_rpcs.sql, plus the offers rules: dates must be YYYY-MM-DD (`format`) and within
-- `maxDaysAhead` (`max_days_ahead`); an `equals: true` toggle must be true (`equals`, also when missing);
-- `optionsFrom: catalog.offerCtaKinds` allows the agent kinds only; offerRef must be an object and offerList an
-- array within maxItems (their references are checked by private.validate_site_offers).
create or replace function private.validate_fields(
  p_fields jsonb, p_obj jsonb, p_section text, p_item int, p_interests text[])
returns jsonb
language plpgsql
stable
set search_path = ''
as $$
declare
  f        jsonb;
  v        jsonb;
  k        text;
  t        text;
  allowed  text[];
  elem     jsonb;
  i        int;
  d        date;
  errs     jsonb := '[]'::jsonb;
  is_empty boolean;
begin
  if jsonb_typeof(p_obj) is distinct from 'object' then
    p_obj := '{}'::jsonb;
  end if;

  for f in select * from jsonb_array_elements(coalesce(p_fields, '[]'::jsonb)) loop
    k := f ->> 'key';
    t := f ->> 'type';
    v := p_obj -> k;
    is_empty := v is null
      or jsonb_typeof(v) = 'null'
      or (jsonb_typeof(v) = 'string' and btrim(v #>> '{}') = '')
      or (jsonb_typeof(v) = 'array' and jsonb_array_length(v) = 0);

    if is_empty then
      if f -> 'equals' = 'true'::jsonb then
        errs := errs || jsonb_build_array(jsonb_build_object(
          'section', p_section, 'field', k, 'item', p_item, 'rule', 'equals'));
      elsif coalesce((f ->> 'required')::boolean, false) then
        errs := errs || jsonb_build_array(jsonb_build_object(
          'section', p_section, 'field', k, 'item', p_item, 'rule', 'required'));
      end if;
      continue;
    end if;

    -- allowed option keys for select / multiSelect
    allowed := null;
    if f ? 'options' then
      select array_agg(o ->> 'key') into allowed from jsonb_array_elements(f -> 'options') o;
    elsif f ->> 'optionsFrom' = 'catalog.interests' then
      allowed := p_interests;
    elsif f ->> 'optionsFrom' = 'catalog.offerCtaKinds' then
      allowed := coalesce(public.catalog_offer_cta_kinds_agent(), '{}'::text[]);
    end if;

    if t in ('text', 'multiline', 'phone', 'email', 'url', 'image', 'date', 'swatch', 'select') then
      if jsonb_typeof(v) <> 'string' then
        errs := errs || jsonb_build_array(jsonb_build_object('section', p_section, 'field', k, 'item', p_item, 'rule', 'type'));
        continue;
      end if;
      if f ? 'maxLength' and char_length(v #>> '{}') > (f ->> 'maxLength')::int then
        errs := errs || jsonb_build_array(jsonb_build_object('section', p_section, 'field', k, 'item', p_item, 'rule', 'maxLength'));
      end if;
      if (t = 'phone' and private.normalize_in_phone(v #>> '{}') is null)
         or (t = 'email' and (v #>> '{}') !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$')
         or (t = 'url' and (v #>> '{}') !~* '^https?://[^[:space:]]+$') then
        errs := errs || jsonb_build_array(jsonb_build_object('section', p_section, 'field', k, 'item', p_item, 'rule', 'format'));
      end if;
      if t = 'date' then
        d := private.try_date(v #>> '{}');
        if d is null then
          errs := errs || jsonb_build_array(jsonb_build_object('section', p_section, 'field', k, 'item', p_item, 'rule', 'format'));
        elsif f ? 'maxDaysAhead' and d > private.today_ist() + (f ->> 'maxDaysAhead')::int then
          errs := errs || jsonb_build_array(jsonb_build_object('section', p_section, 'field', k, 'item', p_item, 'rule', 'max_days_ahead'));
        end if;
      end if;
      if t = 'select' and allowed is not null and not ((v #>> '{}') = any (allowed)) then
        errs := errs || jsonb_build_array(jsonb_build_object('section', p_section, 'field', k, 'item', p_item, 'rule', 'option'));
      end if;

    elsif t = 'number' then
      if jsonb_typeof(v) <> 'number' then
        errs := errs || jsonb_build_array(jsonb_build_object('section', p_section, 'field', k, 'item', p_item, 'rule', 'type'));
      elsif (f ? 'min' and (v #>> '{}')::numeric < (f ->> 'min')::numeric)
         or (f ? 'max' and (v #>> '{}')::numeric > (f ->> 'max')::numeric) then
        errs := errs || jsonb_build_array(jsonb_build_object('section', p_section, 'field', k, 'item', p_item, 'rule', 'range'));
      end if;

    elsif t = 'toggle' then
      if jsonb_typeof(v) <> 'boolean' then
        errs := errs || jsonb_build_array(jsonb_build_object('section', p_section, 'field', k, 'item', p_item, 'rule', 'type'));
      elsif f -> 'equals' = 'true'::jsonb and v <> 'true'::jsonb then
        errs := errs || jsonb_build_array(jsonb_build_object('section', p_section, 'field', k, 'item', p_item, 'rule', 'equals'));
      end if;

    elsif t = 'multiSelect' then
      if jsonb_typeof(v) <> 'array' then
        errs := errs || jsonb_build_array(jsonb_build_object('section', p_section, 'field', k, 'item', p_item, 'rule', 'type'));
      elsif allowed is not null and exists (
          select 1 from jsonb_array_elements(v) e
           where jsonb_typeof(e) <> 'string' or not ((e #>> '{}') = any (allowed))) then
        errs := errs || jsonb_build_array(jsonb_build_object('section', p_section, 'field', k, 'item', p_item, 'rule', 'option'));
      end if;

    elsif t = 'offerRef' then
      if jsonb_typeof(v) <> 'object' then
        errs := errs || jsonb_build_array(jsonb_build_object('section', p_section, 'field', k, 'item', p_item, 'rule', 'offer_shape'));
      end if;

    elsif t = 'offerList' then
      if jsonb_typeof(v) <> 'array' then
        errs := errs || jsonb_build_array(jsonb_build_object('section', p_section, 'field', k, 'item', p_item, 'rule', 'type'));
      elsif f ? 'maxItems' and jsonb_array_length(v) > (f ->> 'maxItems')::int then
        errs := errs || jsonb_build_array(jsonb_build_object('section', p_section, 'field', k, 'item', p_item, 'rule', 'maxItems'));
      end if;

    elsif t = 'list' then
      if jsonb_typeof(v) <> 'array' then
        errs := errs || jsonb_build_array(jsonb_build_object('section', p_section, 'field', k, 'item', p_item, 'rule', 'type'));
        continue;
      end if;
      if f ? 'maxItems' and jsonb_array_length(v) > (f ->> 'maxItems')::int then
        errs := errs || jsonb_build_array(jsonb_build_object('section', p_section, 'field', k, 'item', p_item, 'rule', 'maxItems'));
      end if;
      i := 0;
      for elem in select * from jsonb_array_elements(v) loop
        errs := errs || private.validate_fields(f -> 'itemFields', elem, p_section, i, p_interests);
        i := i + 1;
      end loop;
    end if;
  end loop;
  return errs;
end;
$$;

-- Offer references in site content (OFFERS.md, "publish_site changes"). Returns {errors, warnings}, each a list of
-- {section, field, item, rule}:
--   errors   offer_shape (not {source: company|agent, id: <uuid>}; a custom offer id that isn't a uuid),
--            duplicate (an offer placed twice in the section; two custom offers with one id),
--            offer_wrong_company (an unknown company offer, or another company's), offer_custom_missing,
--            custom_offers_off (the approved company turned custom offers off),
--            blocked_term (a custom offer's title or summary names a product or an insurer: private.public_text_match
--            against the blocked terms and every company name; field title|summary, item = the custom offer's index;
--            checked while the offers section is shown, or for the custom offer hero.featuredOffer points at);
--   warnings offer_ended, offer_unavailable (not live, archived, inactive company, or an offer of a company the agent
--            requested before but isn't approved for now: a changed, withdrawn or revoked link). Warnings never
--            block publishing; those references are skipped at render.
-- hero.featuredOffer is always checked; offers.items only while the offers section is shown.
create or replace function private.validate_site_offers(p_agent uuid, p_content jsonb)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_uuid     text := '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$';
  v_errs     jsonb := '[]'::jsonb;
  v_warn     jsonb := '[]'::jsonb;
  v_hidden   jsonb := case when jsonb_typeof(p_content -> 'hidden') = 'array' then p_content -> 'hidden' else '[]'::jsonb end;
  v_section  jsonb := case when jsonb_typeof(p_content -> 'offers') = 'object' then p_content -> 'offers' else '{}'::jsonb end;
  v_custom   jsonb := case when jsonb_typeof(v_section -> 'custom') = 'array' then v_section -> 'custom' else '[]'::jsonb end;
  v_mem      public.company_memberships;
  v_company  public.companies;
  v_offer    public.offers;
  v_ids      text[] := '{}';
  v_seen     text[] := '{}';
  v_refs     jsonb := '[]'::jsonb;
  r          record;
  v_src      text;
  v_id       text;
  v_issue    jsonb;
  v_feat_id  text := case when jsonb_typeof(p_content #> '{hero,featuredOffer}') = 'object'
                               and p_content #>> '{hero,featuredOffer,source}' = 'agent'
                          then p_content #>> '{hero,featuredOffer,id}' end;
  v_terms    text[];
  v_field    text;
begin
  select m.* into v_mem from public.company_memberships m where m.agent_id = p_agent and m.status = 'approved';
  if v_mem.id is not null then
    select c.* into v_company from public.companies c where c.id = v_mem.company_id;
  end if;

  -- Custom offer ids are what references point at: uuids, unique.
  for r in select e.value as item, (e.ordinality - 1)::int as idx from jsonb_array_elements(v_custom) with ordinality e loop
    v_id := case when jsonb_typeof(r.item) = 'object' then r.item ->> 'id' end;
    if v_id is null or v_id !~ v_uuid then
      v_errs := v_errs || jsonb_build_array(jsonb_build_object('section', 'offers', 'field', 'id', 'item', r.idx, 'rule', 'offer_shape'));
    elsif v_id = any (v_ids) then
      v_errs := v_errs || jsonb_build_array(jsonb_build_object('section', 'offers', 'field', 'id', 'item', r.idx, 'rule', 'duplicate'));
    else
      v_ids := v_ids || v_id;
    end if;
    -- Public text (DECISIONS #77) for what can render: the section is shown, or the hero features this offer.
    if jsonb_typeof(r.item) = 'object' and (not v_hidden ? 'offers' or (v_id is not null and v_id = v_feat_id)) then
      foreach v_field in array array['title', 'summary'] loop
        if jsonb_typeof(r.item -> v_field) = 'string' then
          if v_terms is null then
            v_terms := private.public_text_terms();
          end if;
          if private.public_text_match(r.item ->> v_field, v_terms) is not null then
            v_errs := v_errs || jsonb_build_array(jsonb_build_object('section', 'offers', 'field', v_field, 'item', r.idx, 'rule', 'blocked_term'));
          end if;
        end if;
      end loop;
    end if;
  end loop;

  if p_content #> '{hero,featuredOffer}' is not null and jsonb_typeof(p_content #> '{hero,featuredOffer}') <> 'null' then
    v_refs := v_refs || jsonb_build_array(jsonb_build_object('section', 'hero', 'field', 'featuredOffer', 'item', null,
                                                             'ref', p_content #> '{hero,featuredOffer}'));
  end if;
  if not v_hidden ? 'offers' and jsonb_typeof(v_section -> 'items') = 'array' then
    for r in select e.value as ref, (e.ordinality - 1)::int as idx from jsonb_array_elements(v_section -> 'items') with ordinality e loop
      v_refs := v_refs || jsonb_build_array(jsonb_build_object('section', 'offers', 'field', 'items', 'item', r.idx, 'ref', r.ref));
    end loop;
  end if;

  for r in select e.value as x from jsonb_array_elements(v_refs) e loop
    v_issue := (r.x - 'ref');
    v_src := case when jsonb_typeof(r.x -> 'ref') = 'object' then r.x #>> '{ref,source}' end;
    v_id := case when jsonb_typeof(r.x -> 'ref') = 'object' then r.x #>> '{ref,id}' end;
    if v_src is null or v_src not in ('company', 'agent') or v_id is null or v_id !~ v_uuid then
      v_errs := v_errs || jsonb_build_array(v_issue || '{"rule": "offer_shape"}');
      continue;
    end if;
    if r.x ->> 'section' = 'offers' then
      if (v_src || ':' || v_id) = any (v_seen) then
        v_errs := v_errs || jsonb_build_array(v_issue || '{"rule": "duplicate"}');
        continue;
      end if;
      v_seen := v_seen || (v_src || ':' || v_id);
    end if;

    if v_src = 'agent' then
      if not v_id = any (v_ids) then
        v_errs := v_errs || jsonb_build_array(v_issue || '{"rule": "offer_custom_missing"}');
      elsif v_company.id is not null and not v_company.allow_custom_offers then
        v_errs := v_errs || jsonb_build_array(v_issue || '{"rule": "custom_offers_off"}');
      elsif (select private.try_date(e ->> 'endsOn') < private.today_ist()
               from jsonb_array_elements(v_custom) e where e ->> 'id' = v_id limit 1) then
        v_warn := v_warn || jsonb_build_array(v_issue || '{"rule": "offer_ended"}');
      end if;
    else
      select o.* into v_offer from public.offers o where o.id = v_id::uuid;
      if v_offer.id is null then
        v_errs := v_errs || jsonb_build_array(v_issue || '{"rule": "offer_wrong_company"}');
      elsif v_mem.id is not null and v_offer.company_id = v_mem.company_id then
        if not v_company.is_active or v_offer.status <> 'live' then
          v_warn := v_warn || jsonb_build_array(v_issue || '{"rule": "offer_unavailable"}');
        elsif v_offer.ends_at <= now() then
          v_warn := v_warn || jsonb_build_array(v_issue || '{"rule": "offer_ended"}');
        end if;
      elsif exists (select 1 from public.company_memberships m
                     where m.agent_id = p_agent and m.company_id = v_offer.company_id) then
        -- A company the agent asked for before but isn't approved for now: keep it, skip it at render.
        v_warn := v_warn || jsonb_build_array(v_issue || '{"rule": "offer_unavailable"}');
      else
        v_errs := v_errs || jsonb_build_array(v_issue || '{"rule": "offer_wrong_company"}');
      end if;
    end if;
  end loop;

  return jsonb_build_object('errors', v_errs, 'warnings', v_warn);
end;
$$;

-- One placed offer as the renderer sees it, in one language; null when it must be skipped (see OFFERS.md,
-- "Public payload additions"). p_company is the agent's approved, active company (or a null row). `interest` (the
-- offer's catalog interest, nullable) is on every offer whatever the CTA kind (fallback images, guide grouping);
-- cta.interest stays on enquire CTAs for compatibility.
create or replace function private.resolve_offer_ref(
  p_ref jsonb, p_custom jsonb, p_company public.companies, p_locale text, p_default text, p_featured boolean)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_offer public.offers;
  v_item  jsonb;
  v_ends  date;
  v_title text;
begin
  if jsonb_typeof(p_ref) <> 'object' or p_ref ->> 'id' is null then
    return null;
  end if;

  if p_ref ->> 'source' = 'company' then
    if p_company.id is null or p_ref ->> 'id' !~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then
      return null;
    end if;
    select o.* into v_offer from public.offers o
     where o.id = (p_ref ->> 'id')::uuid and o.company_id = p_company.id
       and o.status = 'live' and o.starts_at <= now() and o.ends_at > now();
    if v_offer.id is null then
      return null;
    end if;
    v_title := coalesce(nullif(btrim(v_offer.content #>> array[p_locale, 'title']), ''),
                        nullif(btrim(v_offer.content #>> array[p_default, 'title']), ''));
    if v_title is null then
      return null;
    end if;
    return jsonb_build_object(
      'source', 'company', 'id', v_offer.id, 'title', v_title,
      'summary', coalesce(nullif(v_offer.content #>> array[p_locale, 'summary'], ''), nullif(v_offer.content #>> array[p_default, 'summary'], '')),
      'details', coalesce(nullif(v_offer.content #>> array[p_locale, 'details'], ''), nullif(v_offer.content #>> array[p_default, 'details'], '')),
      'badge', coalesce(nullif(v_offer.content #>> array[p_locale, 'badge'], ''), nullif(v_offer.content #>> array[p_default, 'badge'], '')),
      'disclaimer', coalesce(nullif(v_offer.content #>> array[p_locale, 'disclaimer'], ''), nullif(v_offer.content #>> array[p_default, 'disclaimer'], '')),
      'image_url', case when p_featured then null else v_offer.image_url end,
      'cta', case v_offer.cta_kind
               when 'link' then jsonb_build_object('kind', 'link', 'url', v_offer.cta_url)
               when 'enquire' then jsonb_build_object('kind', 'enquire', 'interest', v_offer.interest)
               else jsonb_build_object('kind', v_offer.cta_kind) end,
      'ends_on', (v_offer.ends_at at time zone 'Asia/Kolkata')::date,
      'interest', v_offer.interest,
      'from_agent', false);
  elsif p_ref ->> 'source' = 'agent' then
    if p_company.id is not null and not p_company.allow_custom_offers then
      return null;
    end if;
    select e into v_item from jsonb_array_elements(case when jsonb_typeof(p_custom) = 'array' then p_custom else '[]'::jsonb end) e
     where jsonb_typeof(e) = 'object' and e ->> 'id' = p_ref ->> 'id' limit 1;
    v_ends := private.try_date(v_item ->> 'endsOn');
    v_title := nullif(btrim(coalesce(v_item ->> 'title', '')), '');
    if v_item is null or v_title is null or v_ends is null or v_ends < private.today_ist()
       or v_item -> 'confirmed' is distinct from 'true'::jsonb
       or not coalesce(v_item ->> 'ctaKind', '') = any (coalesce(public.catalog_offer_cta_kinds_agent(), '{}'::text[])) then
      return null;
    end if;
    return jsonb_build_object(
      'source', 'agent', 'id', v_item ->> 'id', 'title', v_title,
      'summary', nullif(btrim(coalesce(v_item ->> 'summary', '')), ''),
      'details', null, 'badge', null, 'disclaimer', null, 'image_url', null,
      'cta', case when v_item ->> 'ctaKind' = 'enquire'
                  then jsonb_build_object('kind', 'enquire', 'interest', v_item ->> 'interest')
                  else jsonb_build_object('kind', v_item ->> 'ctaKind') end,
      'ends_on', v_ends,
      'interest', nullif(btrim(coalesce(v_item ->> 'interest', '')), ''),
      'from_agent', true);
  end if;
  return null;
end;
$$;

-- {company, offers:{featured, items}} for a published site, in the site's language (OFFERS.md, BACKEND.md).
--   * company (DECISIONS #77): {disclaimer} only, never the name or the logo, while the agent's membership is
--     approved and the company active; else null.
--   * Picked offers: hero.featuredOffer and offers.items resolved by private.resolve_offer_ref.
--   * Auto offers (DECISIONS #79): while the offers section isn't hidden and has no items and no custom offers, up to
--     3 of the company's live, running offers (by sort, starts_at, id), resolved the same way (the hero's company
--     offer, if one is picked, is left out). With hero.featuredOffer unset and a template of the `offers` family
--     (catalog_template_family), the first auto offer is featured (image_url null) and the rest are the items.
create or replace function private.site_offers_payload(p_site public.sites)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_default  text := coalesce(public.catalog_default_locale(), 'en');
  v_locale   text := case when p_site.locale = any (coalesce(public.catalog_locales(), '{}'::text[])) then p_site.locale else v_default end;
  v_content  jsonb := coalesce(p_site.published_content, '{}'::jsonb);
  v_section  jsonb := case when jsonb_typeof(v_content -> 'offers') = 'object' then v_content -> 'offers' else '{}'::jsonb end;
  v_custom   jsonb := v_section -> 'custom';
  v_hidden   jsonb := case when jsonb_typeof(v_content -> 'hidden') = 'array' then v_content -> 'hidden' else '[]'::jsonb end;
  v_feat_ref jsonb := v_content #> '{hero,featuredOffer}';
  v_feat_set boolean;
  v_company  public.companies;
  v_items    jsonb;
  v_featured jsonb;
  v_auto     boolean;
begin
  select c.* into v_company
    from public.company_memberships m
    join public.companies c on c.id = m.company_id
   where m.agent_id = p_site.agent_id and m.status = 'approved' and c.is_active;

  v_feat_set := v_feat_ref is not null and jsonb_typeof(v_feat_ref) <> 'null';
  v_auto := v_company.id is not null
        and not v_hidden ? 'offers'
        and coalesce(jsonb_array_length(case when jsonb_typeof(v_section -> 'items') = 'array' then v_section -> 'items' end), 0) = 0
        and coalesce(jsonb_array_length(case when jsonb_typeof(v_custom) = 'array' then v_custom end), 0) = 0;

  if v_auto then
    select coalesce(jsonb_agg(a.o order by a.rn), '[]'::jsonb) into v_items
      from (select x.o, row_number() over (order by x.sort, x.starts_at, x.id) as rn
              from (select private.resolve_offer_ref(jsonb_build_object('source', 'company', 'id', o.id), null, v_company,
                                                     v_locale, v_default, false) as o, o.sort, o.starts_at, o.id
                      from public.offers o
                     where o.company_id = v_company.id and o.status = 'live'
                       and o.starts_at <= now() and o.ends_at > now()
                       and not (v_feat_set and jsonb_typeof(v_feat_ref) = 'object' and v_feat_ref ->> 'source' = 'company'
                                and o.id::text = v_feat_ref ->> 'id')) x
             where x.o is not null) a
     where a.rn <= 3;
  else
    select coalesce(jsonb_agg(x.o order by x.idx), '[]'::jsonb) into v_items
      from (select private.resolve_offer_ref(e.value, v_custom, v_company, v_locale, v_default, false) as o, e.ordinality as idx
              from jsonb_array_elements(case when jsonb_typeof(v_section -> 'items') = 'array'
                                             then v_section -> 'items' else '[]'::jsonb end) with ordinality e) x
     where x.o is not null;
  end if;

  if v_feat_set then
    v_featured := private.resolve_offer_ref(v_feat_ref, v_custom, v_company, v_locale, v_default, true);
  elsif v_auto and public.catalog_template_family(p_site.template_key) = 'offers' and jsonb_array_length(v_items) > 0 then
    v_featured := (v_items -> 0) || jsonb_build_object('image_url', null);
    v_items := v_items - 0;
  end if;

  return jsonb_build_object(
    'company', case when v_company.id is null then null else jsonb_build_object(
      'disclaimer', coalesce(nullif(v_company.disclaimer ->> v_locale, ''), nullif(v_company.disclaimer ->> v_default, ''))) end,
    'offers', jsonb_build_object('featured', v_featured, 'items', v_items));
end;
$$;


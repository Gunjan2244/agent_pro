-- An active (not revoked) admins row for the caller, with p_role if given, in an MFA-verified session (aal2).
create or replace function public.is_admin(p_role text default null)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((select auth.jwt() ->> 'aal') = 'aal2', false)
     and exists (
       select 1 from public.admins a
        where a.user_id = (select auth.uid())
          and a.revoked_at is null
          and (p_role is null or a.role = p_role));
$$;


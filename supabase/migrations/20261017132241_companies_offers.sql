-- Insurance companies. Names and disclaimers are stored per catalog locale ({"en": "…", "hi": "…"}), checked by
-- private.companies_guard. Never hard-deleted (is_active = false hides a company everywhere).
create table public.companies (
  id                    uuid primary key default gen_random_uuid(),
  slug                  text not null,
  name                  jsonb not null,
  website_url           text,
  disclaimer            jsonb,
  logo_url              text,
  logo_permission_at    date,
  logo_permission_ref   text,
  logo_permission_until date,
  allow_custom_offers   boolean not null default true,
  is_active             boolean not null default true,
  sort                  integer not null default 0,
  created_by            uuid,
  updated_by            uuid,
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now(),
  constraint companies_slug_key unique (slug),
  constraint companies_slug_format check (slug ~ '^[a-z0-9-]{2,40}$'),
  constraint companies_website_url_https check (website_url is null or website_url ~* '^https://[^[:space:]]+$'),
  constraint companies_logo_url_https check (logo_url is null or logo_url ~* '^https://[^[:space:]]+$'),
  -- A logo needs a recorded written permission (CLAUDE.md, Branding; DECISIONS #47).
  constraint companies_logo_needs_permission check (logo_url is null or logo_permission_at is not null),
  constraint companies_logo_permission_ref_length check (logo_permission_ref is null or char_length(logo_permission_ref) <= 200)
);

-- Company offers. `content` holds offer-schema.json's localized fields per locale ({"en": {...}, "hi": {...}}): the
-- offer's public, generic name and text (DECISIONS #77). internal_name is the real product name, for admins only:
-- it's never in any agent or public payload. status gets its CHECK (offerStatuses) and cta_kind its CHECK
-- (offerCtaKinds) from catalog_sync.
create table public.offers (
  id            uuid primary key default gen_random_uuid(),
  company_id    uuid not null references public.companies (id) on delete restrict,
  status        text not null default 'draft',
  content       jsonb not null default '{}'::jsonb,
  internal_name text,
  image_url     text,
  cta_kind      text not null default 'enquire',
  cta_url       text,
  interest      text,
  starts_at     timestamptz not null,
  ends_at       timestamptz not null,
  sort          integer not null default 0,
  published_at  timestamptz,
  published_by  uuid,
  archived_at   timestamptz,
  created_by    uuid,
  updated_by    uuid,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint offers_dates_order check (ends_at > starts_at),
  constraint offers_internal_name_length check (internal_name is null or char_length(internal_name) <= 120),
  constraint offers_image_url_https check (image_url is null or image_url ~* '^https://[^[:space:]]+$'),
  -- A URL only with the `link` kind, and only https (required for `link` once live: offers_guard).
  constraint offers_cta_url_rule check (cta_url is null or (cta_kind = 'link' and cta_url ~* '^https://[^[:space:]]+$'))
);
create index offers_company_status_ends_idx on public.offers (company_id, status, ends_at);

-- Admin allow-list (chosen over a JWT claim: revocation is immediate and auditable). role gets its CHECK

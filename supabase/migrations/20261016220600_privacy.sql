-- Replace the 8-argument submit_enquiry: PostgREST must see exactly one function.
drop function if exists public.submit_enquiry(text, text, text, text, text, text, text, text);

-- Website enquiry form. Order: resolve site (incl. lapse) -> honeypot -> validate fields -> consent
-- -> rate limit -> insert the enquiry and its consent row (one transaction).
-- consent = {"notice_key":"enquiry_form","version":<current>,"hash":"<64 hex of the text shown>"}.
create or replace function public.submit_enquiry(
  slug text, host text, name text, phone text, email text,
  interest text, message text, honeypot text, consent jsonb default null)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_site     public.sites := private.find_public_site(submit_enquiry.slug, submit_enquiry.host);
  v_honeypot text := btrim(coalesce(submit_enquiry.honeypot, ''));
  v_name     text := btrim(coalesce(submit_enquiry.name, ''));
  v_phone    text := private.normalize_in_phone(submit_enquiry.phone);
  v_email    text := nullif(lower(btrim(coalesce(submit_enquiry.email, ''))), '');
  v_interest text := nullif(btrim(coalesce(submit_enquiry.interest, '')), '');
  v_message  text := nullif(btrim(coalesce(submit_enquiry.message, '')), '');
  v_consent  jsonb;
  v_recent   int;
  v_id       uuid;
begin
  if v_site.id is null then
    return jsonb_build_object('ok', false, 'error', 'unavailable');
  end if;

  -- Honeypot filled: pretend success, store nothing (no enquiry, no consent).
  if v_honeypot <> '' then
    return jsonb_build_object('ok', true);
  end if;

  if char_length(v_name) < 1 or char_length(v_name) > 80 then
    return jsonb_build_object('ok', false, 'error', 'invalid', 'field', 'name');
  end if;
  if v_phone is null then
    return jsonb_build_object('ok', false, 'error', 'invalid', 'field', 'phone');
  end if;
  if v_email is not null and (char_length(v_email) > 120
      or v_email !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$') then
    return jsonb_build_object('ok', false, 'error', 'invalid', 'field', 'email');
  end if;
  if v_interest is not null and not (v_interest = any (coalesce(public.catalog_interest_keys(), '{}'::text[]))) then
    return jsonb_build_object('ok', false, 'error', 'invalid', 'field', 'interest');
  end if;
  if v_message is not null and char_length(v_message) > 500 then
    return jsonb_build_object('ok', false, 'error', 'invalid', 'field', 'message');
  end if;

  -- The enquiry form's notice, current version, hash of the text shown (any locale).
  v_consent := private.resolve_consent(submit_enquiry.consent, 'enquiry_form');
  if v_consent is null then
    return jsonb_build_object('ok', false, 'error', 'invalid', 'field', 'consent');
  end if;

  -- At most 5 submissions per phone per site per rolling hour (soft-deleted rows still count).
  perform pg_advisory_xact_lock(hashtextextended(v_site.id::text || '|' || v_phone, 0));
  select count(*) into v_recent
    from public.enquiries e
   where e.site_id = v_site.id
     and e.phone = v_phone
     and e.source = 'website'
     and e.created_at > now() - interval '1 hour';
  if v_recent >= 5 then
    return jsonb_build_object('ok', false, 'error', 'rate_limited');
  end if;

  insert into public.enquiries (agent_id, site_id, name, phone, email, interest, source, message, status)
  values (v_site.agent_id, v_site.id, v_name, v_phone, v_email, v_interest, 'website', v_message, 'new')
  returning id into v_id;

  insert into public.consents (agent_id, principal_kind, enquiry_id, notice_key, notice_version, notice_hash, locale, channel)
  values (v_site.agent_id, 'enquirer', v_id, v_consent ->> 'notice_key', (v_consent ->> 'version')::int,
          v_consent ->> 'hash', v_consent ->> 'locale', 'web');

  return jsonb_build_object('ok', true);
end;
$$;

-- The site privacy page's request form. Same site resolution, honeypot and phone rule as
-- submit_enquiry; at most 3 requests per phone per site per rolling 24 hours. The request goes to the
-- site's agent (the fiduciary), status 'open' (the initial dataRequestStatuses key), due after
-- app_config.retention.dataRequests.responseDays.
create or replace function public.submit_data_request(
  slug text, host text, name text, phone text, kind text, message text, honeypot text)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_site     public.sites := private.find_public_site(submit_data_request.slug, submit_data_request.host);
  v_honeypot text := btrim(coalesce(submit_data_request.honeypot, ''));
  v_name     text := btrim(coalesce(submit_data_request.name, ''));
  v_phone    text := private.normalize_in_phone(submit_data_request.phone);
  v_kind     text := nullif(btrim(coalesce(submit_data_request.kind, '')), '');
  v_message  text := nullif(btrim(coalesce(submit_data_request.message, '')), '');
  v_days     int;
  v_recent   int;
begin
  if v_site.id is null then
    return jsonb_build_object('ok', false, 'error', 'unavailable');
  end if;

  if v_honeypot <> '' then
    return jsonb_build_object('ok', true);
  end if;

  if char_length(v_name) < 1 or char_length(v_name) > 80 then
    return jsonb_build_object('ok', false, 'error', 'invalid', 'field', 'name');
  end if;
  if v_phone is null then
    return jsonb_build_object('ok', false, 'error', 'invalid', 'field', 'phone');
  end if;
  if v_kind is null or not (v_kind = any (coalesce(public.catalog_data_request_kinds(), '{}'::text[]))) then
    return jsonb_build_object('ok', false, 'error', 'invalid', 'field', 'kind');
  end if;
  if v_message is not null and char_length(v_message) > 500 then
    return jsonb_build_object('ok', false, 'error', 'invalid', 'field', 'message');
  end if;

  perform pg_advisory_xact_lock(hashtextextended('data_request|' || v_site.agent_id::text || '|' || v_phone, 0));
  select count(*) into v_recent
    from public.data_requests r
   where r.agent_id = v_site.agent_id
     and r.phone = v_phone
     and r.created_at > now() - interval '24 hours';
  if v_recent >= 3 then
    return jsonb_build_object('ok', false, 'error', 'rate_limited');
  end if;

  v_days := (private.retention_config() #>> '{dataRequests,responseDays}')::int;
  insert into public.data_requests (agent_id, addressed_to, kind, status, name, phone, message, due_at)
  values (v_site.agent_id, 'agent', v_kind, 'open', v_name, v_phone, v_message,
          now() + make_interval(days => v_days));

  return jsonb_build_object('ok', true);
end;
$$;


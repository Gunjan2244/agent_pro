-- Validate a client consent payload {notice_key, version, hash} for the expected notice (P1-1 contract):
-- the notice is active, version is its CURRENT version, and the hash matches that version's text in some
-- locale. Returns {notice_key, version, hash, locale} or null. Never raises for bad input.
create or replace function private.resolve_consent(p_consent jsonb, p_notice_key text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_current jsonb;
  v_version int;
  v_hash    text;
  v_locale  text;
begin
  if p_consent is null or jsonb_typeof(p_consent) <> 'object' or p_notice_key is null then
    return null;
  end if;
  if jsonb_typeof(p_consent -> 'notice_key') is distinct from 'string'
     or p_consent ->> 'notice_key' <> p_notice_key then
    return null;
  end if;
  if jsonb_typeof(p_consent -> 'version') is distinct from 'number'
     or (p_consent ->> 'version') !~ '^[0-9]{1,9}$' then
    return null;
  end if;
  if jsonb_typeof(p_consent -> 'hash') is distinct from 'string'
     or (p_consent ->> 'hash') !~ '^[0-9a-f]{64}$' then
    return null;
  end if;
  v_version := (p_consent ->> 'version')::int;
  v_hash    := p_consent ->> 'hash';

  v_current := public.catalog_privacy_notice(p_notice_key);
  if v_current is null or (v_current ->> 'version')::int is distinct from v_version then
    return null;
  end if;
  v_locale := public.catalog_privacy_notice_locale(p_notice_key, v_version, v_hash);
  if v_locale is null then
    return null;
  end if;
  return jsonb_build_object('notice_key', p_notice_key, 'version', v_version, 'hash', v_hash, 'locale', v_locale);
end;
$$;

-- app_config('retention') = catalog.retention (from catalog_sync). Fails loudly if it's missing.
create or replace function private.retention_config()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v jsonb;
begin
  select c.value into v from public.app_config c where c.key = 'retention';
  if v is null or v #>> '{dataRequests,responseDays}' is null then
    raise exception 'app_config.retention is missing: apply the generated catalog_sync migration'
      using errcode = 'P0001';
  end if;
  return v;
end;
$$;

-- payments.raw minimisation (PRIVACY.md, Purpose limitation; refines DECISIONS #30): keep only
-- id, order_id, status, method, amount, currency, fee, tax, captured, error_code, error_reason,
-- created_at and acquirer_data.rrn of the provider's payment entity. Everything else (email, contact,
-- vpa, card, bank, wallet, notes, ...) is never stored. A non-object or an empty result is stored as null.
create or replace function private.minimise_payment_raw(p_raw jsonb)
returns jsonb
language sql
immutable
set search_path = ''
as $$
  select case when jsonb_typeof(p_raw) = 'object' then (
    select nullif(
      coalesce((select jsonb_object_agg(e.key, e.value)
                  from jsonb_each(p_raw) e
                 where e.key in ('id', 'order_id', 'status', 'method', 'amount', 'currency', 'fee', 'tax',
                                 'captured', 'error_code', 'error_reason', 'created_at')), '{}'::jsonb)
      || case when jsonb_typeof(p_raw -> 'acquirer_data') = 'object' and (p_raw -> 'acquirer_data') ? 'rrn'
              then jsonb_build_object('acquirer_data', jsonb_build_object('rrn', p_raw #> '{acquirer_data,rrn}'))
              else '{}'::jsonb end,
      '{}'::jsonb)
  ) end;
$$;

-- SECURITY DEFINER because the service role (Edge Functions) fires it and has no usage on `private`.
create or replace function private.payments_minimise_raw()

-- ===========================================================================
-- Signup trigger: also records the agent_signup consent sent as raw_user_meta_data.consent.
-- A missing or invalid consent can't block the Auth signup cleanly, so the user is still created and
-- nothing is recorded; the app must then call record_consent before continuing (UX: sign-up gate).
-- ===========================================================================
create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_trial_days int := (private.service_pricing() ->> 'trialDays')::int;
  v_consent    jsonb := private.resolve_consent(new.raw_user_meta_data -> 'consent', 'agent_signup');
begin
  insert into public.profiles (id, email, full_name, phone)
  values (
    new.id,
    new.email,
    nullif(btrim(new.raw_user_meta_data ->> 'full_name'), ''),
    nullif(btrim(new.raw_user_meta_data ->> 'phone'), '')
  )
  on conflict (id) do nothing;

  insert into public.subscriptions (agent_id, trial_started_at, trial_ends_at)
  values (new.id, now(), now() + make_interval(days => v_trial_days))
  on conflict (agent_id) do nothing;

  if v_consent is not null then
    insert into public.consents (agent_id, principal_kind, notice_key, notice_version, notice_hash, locale, channel)
    values (new.id, 'agent', v_consent ->> 'notice_key', (v_consent ->> 'version')::int,
            v_consent ->> 'hash', v_consent ->> 'locale', 'app');
  end if;

  return new;
end;
$$;


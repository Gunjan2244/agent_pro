-- Agent PRO — P1-2 — privacy backend (docs/PRIVACY.md; DECISIONS #48, #54, #61).
--   * tables consents, data_requests, audit_log (owner-only RLS on the agent tables; audit_log has no
--     API access until the admin tables exist, OFFERS.md);
--   * submit_enquiry gains `consent jsonb` (the old 8-argument overload is dropped, so PostgREST sees
--     one function); submit_data_request (anon); record_consent and update_data_request (authenticated);
--   * the signup trigger records the agent_signup consent sent in raw_user_meta_data.consent;
--   * payments.raw keeps only the allow-listed Razorpay keys (a trigger, so no write path can skip it).
--
-- Generated by the *_catalog_sync.sql that sorts AFTER this file (plpgsql resolves names lazily):
--   public.catalog_privacy_notice(text) / _hash(text, integer, text) / _locale(text, integer, text)
--   public.catalog_data_request_kinds() / catalog_data_request_statuses()
--   app_config('retention')  (dataRequests.responseDays)
--   CHECKs consents_notice_key_check, data_requests_kind_check, data_requests_status_check.
-- Never compute or hard-code a notice hash here (BACKEND.md, consent validation contract).

-- ===========================================================================
-- Tables
-- ===========================================================================

-- Consent records. One row per consent given; no IP address or device data (minimisation).
-- notice_key gets its CHECK from catalog_sync (privacyNotices). principal_kind, channel and
-- withdrawn_via are internal value lists (PRIVACY.md), like orders.status.
create table public.consents (
  id             uuid primary key default gen_random_uuid(),
  agent_id       uuid not null references auth.users (id) on delete cascade,  -- the fiduciary context
  principal_kind text not null,
  enquiry_id     uuid,
  customer_id    uuid,
  notice_key     text not null,                -- CHECK from catalog_sync (privacyNotices)
  notice_version integer not null,
  notice_hash    text not null,
  locale         text not null,                -- resolved from the hash, never sent by the client
  channel        text not null,
  given_at       timestamptz not null default now(),
  withdrawn_at   timestamptz,
  withdrawn_via  text,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  deleted_at     timestamptz,
  constraint consents_principal_kind_values check (principal_kind in ('agent', 'enquirer', 'customer')),
  constraint consents_channel_values check (channel in ('app', 'web')),
  constraint consents_withdrawn_via_values check (withdrawn_via is null or withdrawn_via in ('web_form', 'agent', 'app')),
  constraint consents_withdrawn_pair check ((withdrawn_at is null) = (withdrawn_via is null)),
  constraint consents_notice_version_positive check (notice_version >= 1),
  constraint consents_notice_hash_format check (notice_hash ~ '^[0-9a-f]{64}$'),
  constraint consents_enquiry_fk foreign key (enquiry_id, agent_id)
    references public.enquiries (id, agent_id) on delete set null (enquiry_id),
  constraint consents_customer_fk foreign key (customer_id, agent_id)
    references public.customers (id, agent_id) on delete set null (customer_id)
);
create index consents_agent_id_updated_at_idx on public.consents (agent_id, updated_at);
create index consents_enquiry_id_idx on public.consents (enquiry_id, agent_id);
create index consents_customer_id_idx on public.consents (customer_id, agent_id);


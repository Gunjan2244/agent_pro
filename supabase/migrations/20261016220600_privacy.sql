-- Record the caller's own consent to a notice shown in the app:
--   agent_signup, agent_customer_duty -> principal 'agent', customer_id must be null;
--   guardian_consent                   -> principal 'customer', customer_id (one of the caller's live
--                                         customers) required;
--   enquiry_form                       -> refused (only submit_enquiry records it).
-- Idempotent: a live, unwithdrawn consent to the same notice version (and customer) returns ok without a
-- new row. Returns {ok:true} | {ok:false, error:'invalid', field:'consent'|'customer_id'};
-- raises not_found (P0002) for a customer the caller doesn't own.
create or replace function public.record_consent(
  notice_key text, version integer, hash text, customer_id uuid default null)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_uid      uuid := private.require_uid();
  v_key      text := record_consent.notice_key;
  v_customer uuid := record_consent.customer_id;
  v_consent  jsonb;
  v_kind     text;
begin
  if v_key is null or v_key = 'enquiry_form' then
    return jsonb_build_object('ok', false, 'error', 'invalid', 'field', 'consent');
  end if;
  v_consent := private.resolve_consent(
    jsonb_build_object('notice_key', v_key, 'version', record_consent.version, 'hash', record_consent.hash), v_key);
  if v_consent is null then
    return jsonb_build_object('ok', false, 'error', 'invalid', 'field', 'consent');
  end if;

  if v_key = 'guardian_consent' then
    v_kind := 'customer';
    if v_customer is null then
      return jsonb_build_object('ok', false, 'error', 'invalid', 'field', 'customer_id');
    end if;
    if not exists (select 1 from public.customers c
                    where c.id = v_customer and c.agent_id = v_uid and c.deleted_at is null) then
      raise exception 'not_found' using errcode = 'P0002';
    end if;
  else
    v_kind := 'agent';
    if v_customer is not null then
      return jsonb_build_object('ok', false, 'error', 'invalid', 'field', 'customer_id');
    end if;
  end if;

  perform pg_advisory_xact_lock(hashtextextended('consent|' || v_uid::text || '|' || v_key, 0));
  if exists (select 1 from public.consents k
              where k.agent_id = v_uid
                and k.notice_key = v_key
                and k.notice_version = (v_consent ->> 'version')::int
                and k.customer_id is not distinct from v_customer
                and k.withdrawn_at is null
                and k.deleted_at is null) then
    return jsonb_build_object('ok', true);
  end if;

  insert into public.consents (agent_id, principal_kind, customer_id, notice_key, notice_version, notice_hash, locale, channel)
  values (v_uid, v_kind, v_customer, v_key, (v_consent ->> 'version')::int,
          v_consent ->> 'hash', v_consent ->> 'locale', 'app');
  return jsonb_build_object('ok', true);
end;
$$;

-- Set the status of one of the caller's requests (status in catalog_data_request_statuses()), with an
-- optional note (<= 500). resolved_at is set when the request leaves 'open' and cleared if it's reopened.
-- Writes an audit_log row (no note, no personal data). Returns {id, status, resolved_at}.
-- Errors: not_found (P0002), invalid_status / invalid_note (22023).
create or replace function public.update_data_request(id uuid, status text, note text)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_uid    uuid := private.require_uid();
  v_status text := update_data_request.status;
  v_note   text := nullif(btrim(coalesce(update_data_request.note, '')), '');
  v_row    public.data_requests;
  v_resolved timestamptz;
begin
  if v_status is null or not (v_status = any (coalesce(public.catalog_data_request_statuses(), '{}'::text[]))) then
    raise exception 'invalid_status' using errcode = '22023';
  end if;
  if v_note is not null and char_length(v_note) > 500 then
    raise exception 'invalid_note' using errcode = '22023';
  end if;

  select r.* into v_row from public.data_requests r
   where r.id = update_data_request.id
     and r.agent_id = v_uid
     and r.addressed_to = 'agent'
     and r.deleted_at is null
   for update;
  if v_row.id is null then
    raise exception 'not_found' using errcode = 'P0002';
  end if;

  v_resolved := case
    when v_status = 'open' then null
    when v_row.status = v_status then coalesce(v_row.resolved_at, now())
    else now()
  end;

  update public.data_requests r
     set status = v_status, resolution_note = v_note, resolved_at = v_resolved
   where r.id = v_row.id;

  insert into public.audit_log (actor_id, actor_kind, action, entity, entity_id, changes)
  values (v_uid, 'agent', 'data_request.update', 'data_requests', v_row.id,
          jsonb_build_object('status', v_status, 'previous_status', v_row.status));

  return jsonb_build_object('id', v_row.id, 'status', v_status, 'resolved_at', v_resolved);
end;

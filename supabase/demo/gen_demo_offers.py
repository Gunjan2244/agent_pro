#!/usr/bin/env python3
"""Generates supabase/demo/demo_offers.sql from supabase/demo/demo-offers.json (TEST DATA ONLY).

Run:  python3 -I supabase/demo/gen_demo_offers.py
Stdlib only. The output is a seed script, not a migration: see its header (and docs/BACKEND.md, "Demo seed")
for how and where it may be run. Offer ids are uuid5 values derived from the company slug and the offer key, so
re-running the script updates the same rows. The JSON's `image` field names a bundled web image for the web
fixtures only; the SQL seed leaves image_url null.
"""
import json
import pathlib
import uuid

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE / "demo-offers.json"
OUT = HERE / "demo_offers.sql"
NS = uuid.uuid5(uuid.NAMESPACE_URL, "https://agentpro.invalid/demo-offers")


def lit(value):
    """A SQL string literal (standard_conforming_strings: only quotes need doubling)."""
    if value is None:
        return "null"
    return "'" + str(value).replace("'", "''") + "'"


def jsonb(value):
    return lit(json.dumps(value, ensure_ascii=False, sort_keys=True)) + "::jsonb"


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    company = data["company"]
    slug = company["slug"]
    company_id = uuid.uuid5(NS, "company:" + slug)
    lines = [
        "-- GENERATED by supabase/demo/gen_demo_offers.py from supabase/demo/demo-offers.json. Do not edit by hand.",
        "-- TEST DATA ONLY. NOT a migration: never put it in supabase/migrations/.",
        "--",
        "-- Creates (or updates) the demo company '" + slug + "' and its " + str(len(data["offers"])) + " offers, live,",
        "-- with their admin-only internal_name. Idempotent (on conflict). The offers' public text passes the",
        "-- blocked-term check in offers_guard; an offer whose end has passed stays a draft.",
        "--",
        "-- How to run (only with the user's approval for that project; docs/BACKEND.md, \"Demo seed\"):",
        "--   * after every migration has been applied;",
        "--   * as the `postgres` role, e.g. the Supabase SQL Editor (one request = one transaction), or",
        "--     `psql --single-transaction -f supabase/demo/demo_offers.sql`. As the table owner, postgres isn't subject",
        "--     to the admin-only RLS. auth.uid() is null there, so created_by/updated_by/published_by stay null and",
        "--     the audit trail records actor_kind 'system'; the guards allow that.",
        "--   * It has no begin/commit of its own, so a caller (the SQL tests) can run it inside a transaction.",
        "",
        "insert into public.companies (id, slug, name, disclaimer, is_active, sort)",
        "values (" + ", ".join([lit(company_id), lit(slug), jsonb(company["name"]),
                                 jsonb(company.get("disclaimer")) if company.get("disclaimer") else "null",
                                 "true", "100"]) + ")",
        "on conflict (slug) do update",
        "  set name = excluded.name, disclaimer = excluded.disclaimer, is_active = true;",
        "",
    ]
    ids = []
    for offer in data["offers"]:
        offer_id = uuid.uuid5(NS, "offer:" + slug + ":" + offer["key"])
        ids.append(offer_id)
        starts = offer["startsAt"] + " 00:00:00+05:30"
        ends = offer["endsAt"] + " 23:59:59+05:30"
        lines += [
            "-- " + offer["key"],
            "insert into public.offers (id, company_id, content, internal_name, image_url, cta_kind, interest, starts_at, ends_at, sort)",
            "select " + ", ".join([lit(offer_id), "c.id", jsonb(offer["content"]), lit(offer["internalName"]), "null",
                                   lit(offer["ctaKind"]), lit(offer.get("interest")), lit(starts) + "::timestamptz",
                                   lit(ends) + "::timestamptz", str(int(offer["sort"]))]),
            "  from public.companies c where c.slug = " + lit(slug),
            "on conflict (id) do update",
            "  set content = excluded.content, internal_name = excluded.internal_name, image_url = excluded.image_url,",
            "      cta_kind = excluded.cta_kind, interest = excluded.interest, starts_at = excluded.starts_at,",
            "      ends_at = excluded.ends_at, sort = excluded.sort;",
            "",
        ]
    id_list = ", ".join(lit(i) for i in ids)
    lines += [
        "-- Live: archived -> draft -> live (the guard's transitions). Offers already past their end stay drafts.",
        "update public.offers set status = 'draft' where id in (" + id_list + ") and status = 'archived';",
        "update public.offers set status = 'live' where id in (" + id_list + ") and status = 'draft' and ends_at > now();",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("wrote " + str(OUT.relative_to(HERE.parent.parent)))


if __name__ == "__main__":
    main()

// Generates supabase/demo/demo_sites.sql (TEST DATA ONLY): re-seeds the two demo agents' sites on AGENT_PRO with
// the website-v2 starter content (DECISIONS #78) and links them to the demo company (supabase/demo/demo_offers.sql
// must run first). Run:  node supabase/demo/gen_demo_sites.mjs
//
// The content comes from scripts/site-seed.mjs (the Node mirror of StarterContent.from). Two differences from the
// app, both because this runs without reading anyone's personal data:
//   * the variant seed is the slug, not the agent's user id;
//   * the SQL keeps each site's existing `contact` section, hero photo and designation server-side, so phones,
//     emails and photos never leave the database. The persona names and cities are the demo ones in docs/STATUS.md.
import { writeFileSync, readFileSync } from "node:fs";
import { starterContent } from "../../scripts/site-seed.mjs";

const R = (p) => JSON.parse(readFileSync(new URL("../../" + p, import.meta.url)));
const dicts = { en: R("shared/i18n/en.json"), hi: R("shared/i18n/hi.json") };
const registry = R("shared/templates/index.json");

// Ramesh stays on the "Meet me" family; Priya moves to "Best offers" so the preview shows both families.
// One other test site can be refilled the same way, with the name and city it already shows publicly:
//   node supabase/demo/gen_demo_sites.mjs --slug gunjan --name Gunjan --city Ranchi --template spotlight
const arg = (k) => { const i = process.argv.indexOf("--" + k); return i > 0 ? process.argv[i + 1] : undefined; };
const SITES = arg("slug")
  ? [{ slug: arg("slug"), templateKey: arg("template") || "classic", locale: arg("locale") || "en", profile: { fullName: arg("name"), city: arg("city") || "" } }]
  : [
      { slug: "ramesh-kumar-pune", templateKey: "classic", locale: "en", profile: { fullName: "Ramesh Kumar", city: "Pune" } },
      { slug: "priya-sharma-jaipur", templateKey: "spotlight", locale: "en", profile: { fullName: "Priya Sharma", city: "Jaipur" } },
    ];
const OUT = arg("slug") ? `./refill_${arg("slug")}.sql` : "./demo_sites.sql";
// --no-link: don't link the agent to the demo company (for a "Meet me" site, which shows no offers).
const NO_LINK = process.argv.includes("--no-link");
const COMPANY = "demo-life";
const lit = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const slugs = SITES.map((s) => lit(s.slug)).join(", ");

const blocks = SITES.map(({ slug, templateKey, locale, profile }) => {
  const tpl = registry.templates.find((t) => t.key === templateKey);
  const c = starterContent({ profile, templateKey, locale, agentId: slug, dicts });
  // contact, hero photo and designation are merged in from the stored content below; drop the seed's versions.
  delete c.contact;
  return `-- ${slug}: ${templateKey} (${tpl.family}), ${locale}
update public.sites s
   set template_key = ${lit(templateKey)},
       accent = ${lit(tpl.defaultAccent)},
       locale = ${lit(locale)},
       draft_content = v.content,
       published_content = v.content,
       published_at = now()
  from (select s2.id,
               ${lit(JSON.stringify(c))}::jsonb
               || jsonb_build_object('contact', coalesce(s2.published_content -> 'contact', s2.draft_content -> 'contact', '{}'::jsonb))
               || jsonb_build_object('hero', (${lit(JSON.stringify(c.hero || {}))}::jsonb)
                    || jsonb_strip_nulls(jsonb_build_object('photo', s2.published_content #> '{hero,photo}')))
               || jsonb_build_object('about', (${lit(JSON.stringify(c.about || {}))}::jsonb)
                    || jsonb_strip_nulls(jsonb_build_object('designation', s2.published_content #> '{about,designation}')))
               as content
          from public.sites s2
         where s2.slug = ${lit(slug)} and s2.deleted_at is null) v
 where s.id = v.id;`;
});

const sql = `-- TEST DATA ONLY. Generated by supabase/demo/gen_demo_sites.mjs; do not edit by hand.
-- Re-seeds the demo sites (${SITES.map((s) => s.slug).join(", ")}) with the website-v2 starter content and links
-- their agents to the demo company '${COMPANY}' (approved). Run as postgres in the SQL Editor AFTER
-- every migration (20261022090000_multi_company.sql included) and supabase/demo/demo_offers.sql.
-- Idempotent. Keeps each site's contact section, hero photo and designation (they never leave the database).
begin;
${NO_LINK ? "\n-- No company link (--no-link): a \"Meet me\" site shows no offers.\n" : `
-- Company links: a pending request, then approved (the memberships guard only allows that path). Each link needs
-- at least one insurance type (DECISIONS #89); the demo company is a life insurer.
insert into public.company_memberships (agent_id, company_id, insurance_types)
select s.agent_id, c.id, array['life']
  from public.sites s
  join public.companies c on c.slug = ${lit(COMPANY)}
 where s.slug in (${slugs}) and s.deleted_at is null
   and not exists (select 1 from public.company_memberships m
                    where m.agent_id = s.agent_id and m.company_id = c.id and m.status in ('pending', 'approved'));
update public.company_memberships m
   set status = 'approved'
  from public.sites s, public.companies c
 where s.slug in (${slugs}) and s.deleted_at is null
   and c.slug = ${lit(COMPANY)} and m.agent_id = s.agent_id and m.company_id = c.id and m.status = 'pending';
`}
${blocks.join("\n\n")}

commit;

-- Check (public data only): both sites render with offers and no company name.
select s.slug, s.template_key,
       jsonb_array_length(coalesce(public.get_public_site(s.slug) #> '{offers,items}', '[]'::jsonb)) as offers,
       public.get_public_site(s.slug) -> 'company' as company
  from public.sites s where s.slug in (${slugs});
`;
writeFileSync(new URL(OUT, import.meta.url), sql);
console.log("wrote supabase/demo/" + OUT.slice(2));

#!/usr/bin/env python3
"""Generates supabase/live-data/company_plans_seed.sql from supabase/live-data/company-plans.json (DECISIONS #129).

Run:  python3 -I supabase/live-data/gen_company_plans.py
Stdlib only. The output is a data script for the live project (run as postgres, after
20261031090000_company_plans.sql): it sets each company's official website (and its current name where the
insurer was renamed), then inserts or updates every plan. Plan ids are uuid5 values from the company slug and the
plan name, so re-running it updates the same rows. It never deactivates anything (admins may have added plans of
their own): withdraw a plan in the admin panel.
Checks before writing: plan types against shared/catalog.json (never "other"), insurance types derived from it,
https links on the company's own website, UIN and plan-number formats, no duplicate names per company.
"""
import json
import pathlib
import re
import sys
import uuid

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SRC = HERE / "company-plans.json"
OUT = HERE / "company_plans_seed.sql"
NS = uuid.uuid5(uuid.NAMESPACE_URL, "https://agentpro.invalid/company-plans")


def lit(value):
    if value is None:
        return "null"
    return "'" + str(value).replace("'", "''") + "'"


def host(url):
    m = re.match(r"^https://([^/:?#]+)", url, re.I)
    return re.sub(r"^www\.", "", m.group(1).lower()) if m else None


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    catalog = json.loads((ROOT / "shared" / "catalog.json").read_text(encoding="utf-8"))
    types = {i["key"]: i.get("insuranceType") for i in catalog["interests"]}
    errors, out = [], []
    checked = data["checkedOn"]
    out.append("-- GENERATED by supabase/live-data/gen_company_plans.py from company-plans.json. Do not edit by hand.")
    out.append(f"-- Official plans as published on each insurer's website, checked on {checked} (DECISIONS #129).")
    out.append("-- Run as postgres after 20261031090000_company_plans.sql. Idempotent.")
    out.append("begin;")
    for slug, co in data["companies"].items():
        site = co["websiteUrl"]
        if not host(site):
            errors.append(f"{slug}: websiteUrl must be https")
        sets = [f"website_url = {lit(site)}"]
        if co.get("renamedTo"):
            sets.append(f"name = {lit(json.dumps(co['renamedTo'], ensure_ascii=False, sort_keys=True))}::jsonb")
        out.append(f"update public.companies set {', '.join(sets)} where slug = {lit(slug)};")
        seen = set()
        rows = []
        for n, p in enumerate(co["plans"], start=1):
            name = re.sub(r"\s+", " ", p["name"]).strip()
            key = name.lower()
            if key in seen:
                errors.append(f"{slug}: duplicate plan {name}")
            seen.add(key)
            interest = p["interest"]
            itype = types.get(interest)
            if interest == "other" or not itype:
                errors.append(f"{slug}/{name}: bad interest {interest}")
            h, sh = host(p["url"]), host(site)
            if not h or not (h == sh or h.endswith("." + sh)):
                errors.append(f"{slug}/{name}: url not on {sh}: {p['url']}")
            uin = p.get("uin")
            if uin and not re.fullmatch(r"[A-Z0-9]{6,24}", uin.upper()):
                errors.append(f"{slug}/{name}: bad UIN {uin}")
            plan_no = p.get("planNo")
            if plan_no and not re.fullmatch(r"[A-Za-z0-9-]{1,12}", plan_no):
                errors.append(f"{slug}/{name}: bad plan no {plan_no}")
            pid = uuid.uuid5(NS, f"{slug}/{key}")
            rows.append(f"  ({lit(str(pid))}::uuid, {lit(name)}, {lit(plan_no)}, {lit(uin)}, {lit(interest)}, {lit(itype)}, "
                        f"{lit(p['url'])}, {n * 10}, {lit(checked)}::date)")
        out.append("insert into public.company_plans (id, company_id, name, plan_no, uin, interest, insurance_type, url, sort, checked_on, is_active)")
        out.append(f"select v.id, c.id, v.name, v.plan_no, v.uin, v.interest, v.insurance_type, v.url, v.sort, v.checked_on, true")
        out.append(f"from public.companies c, (values\n" + ",\n".join(rows) + "\n) as v(id, name, plan_no, uin, interest, insurance_type, url, sort, checked_on)")
        out.append(f"where c.slug = {lit(slug)}")
        out.append("on conflict (id) do update set name = excluded.name, plan_no = excluded.plan_no, uin = excluded.uin, "
                   "interest = excluded.interest, insurance_type = excluded.insurance_type, url = excluded.url, "
                   "sort = excluded.sort, checked_on = excluded.checked_on, is_active = true;")
    out.append("commit;")
    if errors:
        print("\n".join(errors), file=sys.stderr)
        sys.exit(1)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    total = sum(len(c["plans"]) for c in data["companies"].values())
    print(f"wrote {OUT.relative_to(ROOT)}: {len(data['companies'])} companies, {total} plans")


if __name__ == "__main__":
    main()
